// 별지3 세액 계산 검증
// 세율표는 법인세법 §55(2025 개편본), 계산 구조는 §13. 손계산으로 기댓값을 검산했다.

import test from 'node:test';
import assert from 'node:assert/strict';
import { 누진세액, 계산 } from '../src/engine/tax.js';
import { 법인세율 } from '../src/domain/rates.js';

// ── 누진세액 ──────────────────────────────────────────
test('과세표준 2억 이하는 단일구간 9% (2025 개시)', () => {
  const r = 누진세액(100_000_000, 법인세율('2025-01-01'));
  assert.equal(r.세액, 9_000_000);
});

test('과세표준 3억은 2억×9% + 1억×19% = 3,700만 (2025 개시)', () => {
  const r = 누진세액(300_000_000, 법인세율('2025-01-01'));
  assert.equal(r.세액, 18_000_000 + 19_000_000);
});

test('2026 개시 사업연도는 1%p 인상 → 2억 이하 10%', () => {
  const r = 누진세액(100_000_000, 법인세율('2026-01-01'));
  assert.equal(r.세액, 10_000_000);
});

test('과세표준 0이면 세액 0', () => {
  assert.equal(누진세액(0, 법인세율('2025-01-01')).세액, 0);
});

// ── 별지3 전체 ────────────────────────────────────────
test('별지3: 당기순이익 + 조정 → 각사업연도소득', () => {
  const r = 계산({
    당기순이익: 80_000_000, 가산조정: 15_000_000, 차감조정: 5_000_000,
    사업연도개시일: '2025-01-01', 중소기업: true,
  });
  assert.equal(r.각사업연도소득, 90_000_000);
  assert.equal(r.과세표준, 90_000_000);      // 이월결손금 없음
  assert.equal(r.산출세액, Math.floor(90_000_000 * 0.09));
});

test('별지3: 차감납부세액 = 산출세액 − 공제감면 + 가산세 − 기납부', () => {
  const r = 계산({
    당기순이익: 100_000_000, 사업연도개시일: '2025-01-01',
    공제감면세액: 1_500_000, 가산세: 200_000, 기납부세액: 3_000_000,
  });
  assert.equal(r.차감납부세액, r.산출세액 - 1_500_000 + 200_000 - 3_000_000);
});

test('이월결손금: 중소기업은 100% 공제', () => {
  const r = 계산({
    당기순이익: 100_000_000, 이월결손금: 100_000_000,
    중소기업: true, 사업연도개시일: '2025-01-01',
  });
  assert.equal(r.이월결손금공제, 100_000_000); // 소득 전액 공제
  assert.equal(r.과세표준, 0);
});

test('이월결손금: 일반법인은 소득의 80%까지만 공제', () => {
  const r = 계산({
    당기순이익: 100_000_000, 이월결손금: 100_000_000,
    중소기업: false, 사업연도개시일: '2025-01-01',
  });
  assert.equal(r.이월결손금공제, 80_000_000); // 1억의 80%
  assert.equal(r.과세표준, 20_000_000);
});

test('기부금 한도초과는 합계표를 거치지 않고 별지3에서 직접 가산', () => {
  const 기본 = 계산({ 당기순이익: 100_000_000, 사업연도개시일: '2025-01-01' });
  const 기부 = 계산({ 당기순이익: 100_000_000, 기부금한도초과: 10_000_000, 사업연도개시일: '2025-01-01' });
  assert.equal(기부.각사업연도소득 - 기본.각사업연도소득, 10_000_000);
});

test('지방소득세는 같은 과세표준에 독립세율(2억 이하 0.9%)', () => {
  const r = 계산({ 당기순이익: 100_000_000, 사업연도개시일: '2025-01-01' });
  assert.equal(r.지방소득세.산출세액, Math.floor(100_000_000 * 0.009));
});

test('별지3 단계 배열의 마지막은 차감납부세액이고 그 값이 일치한다', () => {
  const r = 계산({ 당기순이익: 100_000_000, 사업연도개시일: '2025-01-01', 기납부세액: 1_000_000 });
  const 최종 = r.단계.at(-1);
  assert.equal(최종.최종, true);
  assert.equal(최종.금액, r.차감납부세액);
});
