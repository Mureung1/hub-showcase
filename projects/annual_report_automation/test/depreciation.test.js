// 감가상각 엔진 검증
//
// ⚠️ 여기 기댓값은 내가 지어낸 게 아니라 세법이 정한 값이다 (research.md §5 교과서 예제).
//    상각률표는 법인세법 시행규칙 별표4에서 왔다. 순환논증이 아니다.

import test from 'node:test';
import assert from 'node:assert/strict';
import { 사용월수, 상각선택, 상각범위액, 시부인 } from '../src/engine/depreciation.js';

const FY2025 = { 사업연도개시일: '2025-01-01', 사업연도종료일: '2025-12-31' };

// ── 상각범위액: 교과서 예제 (research.md §5-4) ──────────
test('기계장치 1억 · 5년 정률법 1년차 = 45,100,000 (별표4 상각률 0.451)', () => {
  const 자산 = { 취득일: '2020-01-01', 취득가: 100_000_000, 기초누계: 0 };
  assert.equal(상각범위액(자산, { 방법: '정률', 내용연수: 5 }, FY2025).금액, 45_100_000);
});

test('기계장치 1억 · 5년 정액법 = 20,000,000 (상각률 0.200)', () => {
  const 자산 = { 취득일: '2020-01-01', 취득가: 100_000_000, 기초누계: 0 };
  assert.equal(상각범위액(자산, { 방법: '정액', 내용연수: 5 }, FY2025).금액, 20_000_000);
});

test('정률법 2년차는 미상각잔액(취득가−누계) 기준', () => {
  const 자산 = { 취득일: '2020-01-01', 취득가: 100_000_000, 기초누계: 45_100_000 };
  assert.equal(상각범위액(자산, { 방법: '정률', 내용연수: 5 }, FY2025).금액,
    Math.floor(54_900_000 * 0.451));
});

// ── 월할 ──────────────────────────────────────────────
test('7월 취득 신규자산은 6/12 월할', () => {
  const 자산 = { 취득일: '2025-07-10', 취득가: 100_000_000, 기초누계: 0 };
  const r = 상각범위액(자산, { 방법: '정액', 내용연수: 5 }, FY2025);
  assert.equal(r.월수, 6);
  assert.equal(r.금액, 10_000_000);
});

test('취득한 달을 1개월로 산입 (12월 취득 = 1개월)', () => {
  assert.equal(사용월수('2025-12-20', '2025-01-01', '2025-12-31'), 1);
});

test('사업연도 개시 전 취득은 12개월', () => {
  assert.equal(사용월수('2019-05-01', '2025-01-01', '2025-12-31'), 12);
});

// ── 법적 제약 강제 ────────────────────────────────────
test('건축물에 정률법을 지정해도 정액법이 강제된다', () => {
  const 자산 = { 구분: '건축물', 방법: '정액', 내용연수: 40 };
  const 선택 = 상각선택(자산, { 방법: '정률', 내용연수: 20 });
  assert.equal(선택.방법, '정액');
  assert.equal(선택.고정, true);
});

test('건축물 40년 정률률은 별표4에 없어 계산 시 에러', () => {
  const 자산 = { 취득일: '2015-01-01', 취득가: 500_000_000, 기초누계: 0 };
  assert.throws(() => 상각범위액(자산, { 방법: '정률', 내용연수: 40 }, FY2025));
});

test('업무용승용차는 5년 정액법으로 강제', () => {
  const 자산 = { 구분: '차량운반구', 방법: '정률', 내용연수: 4, 업무용승용차: true };
  const 선택 = 상각선택(자산);
  assert.equal(선택.방법, '정액');
  assert.equal(선택.내용연수, 5);
});

// ── 시부인 ────────────────────────────────────────────
test('시부인: 회사계상액 > 상각범위액 → 부인액 손금불산입', () => {
  const 자산 = {
    명: '기계', 취득일: '2020-01-01', 취득가: 100_000_000, 기초누계: 0,
    방법: '정액', 내용연수: 5, 회사계상액: 25_000_000, // 한도 2천만 초과
  };
  const r = 시부인(자산, FY2025);
  assert.equal(r.상각범위액, 20_000_000);
  assert.equal(r.부인액, 5_000_000);
  assert.equal(r.추인액, 0);
});

test('시부인: 시인부족 + 전기 부인액 있으면 한도 내 추인', () => {
  const 자산 = {
    명: '기계', 취득일: '2020-01-01', 취득가: 100_000_000, 기초누계: 0,
    방법: '정액', 내용연수: 5, 회사계상액: 15_000_000, // 한도보다 500만 부족
    전기이월부인액: 8_000_000,
  };
  const r = 시부인(자산, FY2025);
  assert.equal(r.부인액, 0);
  assert.equal(r.추인액, 5_000_000); // min(부족 500만, 전기부인 800만) = 500만
});

test('시부인: 시인부족인데 전기 부인액 없으면 그냥 소멸(추인 0)', () => {
  const 자산 = {
    명: '기계', 취득일: '2020-01-01', 취득가: 100_000_000, 기초누계: 0,
    방법: '정액', 내용연수: 5, 회사계상액: 15_000_000,
  };
  assert.equal(시부인(자산, FY2025).추인액, 0);
});
