export interface BsIsGroup {
  key: string;
  label: string;
  kind: '자산' | '자산차감' | '부채' | '자본' | '수익' | '비용';
  core: string[] | ((isRental: boolean) => string[]);
  desc: string | ((isRental: boolean) => string);
  kindOverride?: Record<string, string>;
}

export function resolveCore(g: BsIsGroup, isRental: boolean): string[] {
  return typeof g.core === 'function' ? g.core(isRental) : g.core;
}
export function resolveDesc(g: { desc: string | ((isRental: boolean) => string) }, isRental: boolean): string {
  return typeof g.desc === 'function' ? g.desc(isRental) : g.desc;
}

