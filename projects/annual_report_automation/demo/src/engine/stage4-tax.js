const 잔액 = (시산표, 코드) => 시산표.행.find((r) => r.계정 === 코드)?.잔액 ?? 0;

/** 법인세율 — 사업연도 개시일 기준으로 자동 분기 (2025 세제개편: 2026 개시분부터 1%p 인상) */
export function 법인세율구간(개시일) {
  return 개시일 >= '2026-01-01'
    ? [
        { 한도: 200_000_000, 율: 0.10, 명: '2억 이하' },
        { 한도: 20_000_000_000, 율: 0.20, 명: '2억~200억' },
        { 한도: 300_000_000_000, 율: 0.22, 명: '200억~3,000억' },
        { 한도: Infinity, 율: 0.25, 명: '3,000억 초과' },
      ]
    : [
        { 한도: 200_000_000, 율: 0.09, 명: '2억 이하' },
        { 한도: 20_000_000_000, 율: 0.19, 명: '2억~200억' },
        { 한도: 300_000_000_000, 율: 0.21, 명: '200억~3,000억' },
        { 한도: Infinity, 율: 0.24, 명: '3,000억 초과' },
      ];
}

