  const 가산 = 조정.filter((a) => ['익금산입', '손금불산입'].includes(a.구분));
  const 차감 = 조정.filter((a) => ['손금산입', '익금불산입'].includes(a.구분));
  const 가산계 = 가산.reduce((s, a) => s + a.금액, 0);
