// 2단계 — 결산 (결산수정분개 → 합계잔액시산표)
//
// 1단계 전표는 "실제로 돈이 오간 거래"만 담고 있다.
// 결산은 여기에 "돈은 안 오갔지만 회계적으로 인식해야 하는 것"을 얹어 장부를 마감한다.

import { 계정, 차변계정 } from '../data/accounts.js';
import { 기간비용계약 } from '../data/mock.js';
import { 상각범위액, 상각선택 } from './depreciation.js';

/** 일수 차이 (선급비용 안분용) */
const 일수 = (a, b) => Math.round((new Date(b) - new Date(a)) / 86400000) + 1;

/** 감가상각 결산분개 생성 */
export function 감가상각분개(자산대장, 회사, 사용자선택) {
  return 자산대장.map((자산) => {
    const 선택 = 상각선택(자산, 사용자선택);
    const 범위 = 상각범위액(자산, 선택, 회사);
    // 회계 계상액: 데모에서는 세법 상각범위액과 동일하게 계상 (실무 최다 패턴)
    const 계상액 = 범위.금액;
    return {
      자산: 자산.명, 자산id: 자산.id,
      방법: 선택.방법, 내용연수: 선택.내용연수, 고정됨: 선택.고정됨, 사유: 선택.사유,
      금액: 계상액, 산식: 범위.산식,
      분개: [
        { 계정: '607', 차변: 계상액 },
        { 계정: 자산.누계계정, 대변: 계상액 },
      ],
    };
  });
}

/** 선급비용 안분 — 지급액 × 미경과일수 / 총일수 */
export function 선급비용분개(전표, 회사) {
  return 기간비용계약.map((계약) => {
    const 총 = 일수(계약.시작일, 계약.종료일);
    const 미경과 = 일수(
      new Date(new Date(회사.사업연도종료일).getTime() + 86400000).toISOString().slice(0, 10),
      계약.종료일,
    );
    const 금액 = Math.floor((계약.지급액 * 미경과) / 총);
    return {
      계약: 계약.거래키, 금액,
      산식: `지급액 ${계약.지급액.toLocaleString()} × 미경과 ${미경과}일 / 총 ${총}일 = ${금액.toLocaleString()}`,
      분개: [
        { 계정: '102', 차변: 금액 },   // 선급비용(자산)으로 대체
        { 계정: '606', 대변: 금액 },   // 당기 보험료 감소
      ],
    };
  });
}

/** 법인세비용 계상 — 4단계 결과를 받아야 확정 (순환 참조) */
export function 법인세분개(법인세비용, 선납세금) {
  if (법인세비용 <= 0) return null;
  const 미지급 = 법인세비용 - 선납세금;
  return {
    금액: 법인세비용,
    산식: `법인세 산출세액 + 지방소득세 = ${법인세비용.toLocaleString()} ` +
          `(선납세금 ${선납세금.toLocaleString()} 상계 → 미지급 ${미지급.toLocaleString()})`,
    분개: [
      { 계정: '609', 차변: 법인세비용 },
      { 계정: '103', 대변: 선납세금 },     // 선납세금(자산) 소멸
      { 계정: '303', 대변: 미지급 },       // 미지급법인세(부채)
    ],
  };
}

/** 전표 묶음 → 합계잔액시산표 */
export function 시산표생성(전표묶음, 기초잔액) {
  const 집계 = {};
  const 담기 = (계정코드, 차 = 0, 대 = 0) => {
    집계[계정코드] ??= { 계정: 계정코드, 명: 계정[계정코드].명, 차변합계: 0, 대변합계: 0 };
    집계[계정코드].차변합계 += 차;
    집계[계정코드].대변합계 += 대;
  };

  for (const b of 기초잔액) 담기(b.계정, b.차변 ?? 0, b.대변 ?? 0);
  for (const e of 전표묶음) for (const l of e.분개) 담기(l.계정, l.차변 ?? 0, l.대변 ?? 0);

  const 행 = Object.values(집계)
    .map((r) => {
      const 순 = r.차변합계 - r.대변합계;
      return { ...r, 잔액: Math.abs(순), 잔액방향: 순 >= 0 ? '차변' : '대변' };
    })
    .sort((a, b) => a.계정.localeCompare(b.계정));

  const 합계 = 행.reduce(
    (s, r) => ({
      차변합계: s.차변합계 + r.차변합계,
      대변합계: s.대변합계 + r.대변합계,
      차변잔액: s.차변잔액 + (r.잔액방향 === '차변' ? r.잔액 : 0),
      대변잔액: s.대변잔액 + (r.잔액방향 === '대변' ? r.잔액 : 0),
    }),
    { 차변합계: 0, 대변합계: 0, 차변잔액: 0, 대변잔액: 0 },
  );

  return {
    행, 합계,
    // 대차평형: 전기(轉記) 오류만 잡는다. 계정 착오(분개 자체의 오류)는 못 잡는다.
    대차평형: 합계.차변합계 === 합계.대변합계 && 합계.차변잔액 === 합계.대변잔액,
  };
}

/** 2단계 실행 */
export function runStage2({ 전표, 기초잔액, 자산대장, 회사, 사용자선택 = {}, 법인세비용 = 0 }) {
  const 감가 = 감가상각분개(자산대장, 회사, 사용자선택);
  const 선급 = 선급비용분개(전표, 회사);

  const 수정전 = 시산표생성(전표, 기초잔액);
  const 선납세금 = 수정전.행.find((r) => r.계정 === '103')?.잔액 ?? 0;
  const 법인세 = 법인세분개(법인세비용, 선납세금);

  const 수정분개 = [
    ...감가.map((d) => ({ 유형: '감가상각', 설명: d.자산, 금액: d.금액, 산식: d.산식, 분개: d.분개 })),
    ...선급.map((p) => ({ 유형: '선급비용', 설명: p.계약, 금액: p.금액, 산식: p.산식, 분개: p.분개 })),
    ...(법인세 ? [{ 유형: '법인세비용', 설명: '당기 법인세 계상', 금액: 법인세.금액, 산식: 법인세.산식, 분개: 법인세.분개 }] : []),
  ];

  const 수정후 = 시산표생성([...전표, ...수정분개], 기초잔액);

  return { 감가, 선급, 법인세, 수정분개, 수정전시산표: 수정전, 시산표: 수정후 };
}
