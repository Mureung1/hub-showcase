// ⚠️ 5단계 산출물(접수증·납부서·영수증)은 "만드는" 대상이 아니다.
//    신고라는 행위의 **부산물**로 저절로 생기는 것이고,
//    신고 자체는 세무사 서명이 법적으로 필요한 영역이라 코드가 대신할 수 없다.
//    이 모듈은 "파이프라인의 종착점이 어디인가"를 보여주기 위한 시뮬레이션일 뿐이다.

/** 법인세법 §60⑤ — 이 4가지를 첨부하지 않으면 신고 자체를 무신고로 본다 */
export const 필수첨부서식 = [
  '재무상태표',
  '(포괄)손익계산서',
  '이익잉여금처분(결손금처리)계산서',
  '세무조정계산서',
];

const 접수번호생성 = (prefix, seed) =>
  `${prefix}-2026-${String(Math.abs(hash(seed)) % 900000 + 100000)}`;

function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return h;
}

export function runStage5({ 별지3, 지방소득세, 회사 }) {
  const 신고기한 = '2026-03-31';   // 12월말 법인: 사업연도 종료일이 속한 달의 말일부터 3개월
  const 지방신고기한 = '2026-04-30'; // 4개월

  return {
    시뮬레이션: true,
    경고: '⚠️ 실제 신고가 아닙니다. 실제 전자신고는 세무사 검토·서명 후에만 가능하며, ' +
          '이 프로젝트의 산출물은 "세무사 전달용 완성 초안"까지입니다.',

    법인세: {
      채널: '홈택스 (hometax.go.kr)',
      접수번호: 접수번호생성('HT', 회사.상호 + 별지3.과세표준),
      접수일시: `${신고기한} 14:32:10`,
      신고기한,
      차감납부세액: 별지3.차감납부세액,
      분납가능: 별지3.차감납부세액 > 10_000_000,
      분납주석: 별지3.차감납부세액 > 10_000_000
        ? `1천만원 초과 → 분납 가능 (중소기업 2개월)`
        : '1천만원 이하 → 분납 대상 아님',
      첨부서식: 필수첨부서식,
      첨부주석: '법인세법 §60⑤ — 위 4가지 미첨부 시 신고 자체를 무신고로 본다 (있으면 좋은 서류가 아니라 신고의 성립요건)',
    },

    지방소득세: {
      채널: '위택스 (wetax.go.kr) — 홈택스가 아님',
      접수번호: 접수번호생성('WT', 회사.상호 + 지방소득세.산출세액),
      접수일시: `${지방신고기한} 10:05:44`,
      신고기한: 지방신고기한,
      납부세액: 지방소득세.산출세액,
      주석: '2014년부터 독립세 — 법인세 과세표준을 쓰되 세율·신고·납부는 지자체에 별도',
    },

    납부서: [
      { 서식: '국세징수법 시행규칙 [별지 제1호서식]', 명: '영수증서(납세자용)', 금액: 별지3.차감납부세액 },
      { 서식: '국세징수법 시행규칙 [별지 제1호서식]', 명: '납부서(수납기관용)', 금액: 별지3.차감납부세액 },
      { 서식: '지방세법 시행규칙 [별지 제43호의8서식]', 명: '법인지방소득세 납부서 겸 영수증', 금액: 지방소득세.산출세액 },
    ],

    총납부액: 별지3.차감납부세액 + 지방소득세.산출세액,
  };
}
