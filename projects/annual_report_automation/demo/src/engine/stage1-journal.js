/**
 * 1단계 실행: 통장내역 → 전표
 * @param {object[]} 통장내역
 * @param {object} 큐답변 - { 큐키: '선택값' } 사람이 확인 큐에서 고른 답. 미지정 시 정답 사용.
 */
export function runStage1(통장내역, 큐답변 = {}) {
  const 전표 = [];
  const 큐 = [];

  for (const t of 통장내역) {
    const 규칙 = 분개규칙.find((r) => r.match(t));

    if (규칙) {
      전표.push({
        id: t.id, 일자: t.일자, 적요: t.적요, 거래처: t.거래처,
        증빙유형: t.증빙유형,           // ★ 4단계 적격증빙 판정이 이 태그를 쓴다
        경로: 규칙.경로, 신뢰도: 규칙.신뢰도,
        근거: `[${규칙.id}] ${규칙.설명}`,
        분개: 규칙.분개(t),
      });
      continue;
    }

    // 미매칭 → 사람 확인 큐
    const 후보 = 확인큐후보.find((q) => q.match(t));
    if (!후보) continue;

    const 선택값 = 큐답변[후보.큐키] ?? 후보.선택지.find((o) => o.정답).값;
    const 선택 = 후보.선택지.find((o) => o.값 === 선택값) ?? 후보.선택지.find((o) => o.정답);

    큐.push({
      큐키: 후보.큐키, 거래: t, 질문: 후보.질문, 이유: 후보.이유,
      선택지: 후보.선택지.map(({ 값, 라벨, 정답, 해설 }) => ({ 값, 라벨, 정답, 해설 })),
      선택값: 선택.값, 정답여부: 선택.정답,
    });

    전표.push({
      id: t.id, 일자: t.일자, 적요: t.적요, 거래처: t.거래처,
      증빙유형: t.증빙유형,
      경로: '사람 확인', 신뢰도: 1.0,
      근거: `확인 큐에서 사람이 [${선택.라벨}]로 확정 — ${후보.이유}`,
      분개: 선택.분개(t),
    });
  }

  const 차변합 = (e) => e.분개.reduce((a, l) => a + (l.차변 ?? 0), 0);
  const 자동 = 전표.filter((e) => e.경로 !== '사람 확인');
  const 자동금액 = 자동.reduce((s, e) => s + 차변합(e), 0);
  const 총금액 = 전표.reduce((s, e) => s + 차변합(e), 0);

  return {
    전표, 큐,
    통계: {
      총거래: 통장내역.length,
      자동확정: 자동.length,
      사람확인: 전표.length - 자동.length,
      자동화율_건수: 전표.length ? 자동.length / 전표.length : 0,
      자동화율_금액: 총금액 ? 자동금액 / 총금액 : 0,
    },
  };
}
