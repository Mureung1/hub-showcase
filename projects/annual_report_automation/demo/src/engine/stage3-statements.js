// 3단계 — 결산보고서 (재무상태표 · 손익계산서)
//
// 이 단계는 기계적 변환이다. 시산표의 계정 잔액을 재무제표 구조로 재배치할 뿐,
// 새로운 재료가 필요 없다. (보고서-준비물-워크플로우.md §2-1의 [장] 등급)

import { 계정 } from '../data/accounts.js';

const 잔액 = (시산표, 코드) => 시산표.행.find((r) => r.계정 === 코드)?.잔액 ?? 0;

const 그룹 = (시산표, 구분) =>
  시산표.행
    .filter((r) => 계정[r.계정].구분 === 구분 && r.잔액 !== 0)
    .map((r) => ({ 계정: r.계정, 명: r.명, 세부: 계정[r.계정].세부, 금액: r.잔액 }));

export function runStage3({ 시산표 }) {
  // ── 손익계산서 ────────────────────────────────
  const 수익 = 그룹(시산표, '수익');
  const 비용 = 그룹(시산표, '비용');

  const 매출액 = 수익.filter((r) => r.세부 === '매출액').reduce((s, r) => s + r.금액, 0);
  const 판관비 = 비용.filter((r) => r.세부 === '판매비와관리비').reduce((s, r) => s + r.금액, 0);
  const 영업이익 = 매출액 - 판관비;
  const 영업외수익 = 수익.filter((r) => r.세부 === '영업외수익').reduce((s, r) => s + r.금액, 0);
  const 영업외비용 = 비용.filter((r) => r.세부 === '영업외비용').reduce((s, r) => s + r.금액, 0);
  const 법인세차감전순이익 = 영업이익 + 영업외수익 - 영업외비용;
  const 법인세비용 = 잔액(시산표, '609');
  const 당기순이익 = 법인세차감전순이익 - 법인세비용;

  const 손익계산서 = {
    매출액, 판관비, 영업이익, 영업외수익, 영업외비용,
    법인세차감전순이익, 법인세비용, 당기순이익,
    항목: { 수익, 비용 },
    단계: [
      { 라벨: '매출액 (임대료수입)', 금액: 매출액, 강조: false },
      { 라벨: '판매비와관리비', 금액: -판관비, 강조: false },
      { 라벨: '영업이익', 금액: 영업이익, 강조: true },
      { 라벨: '영업외수익 (이자수익)', 금액: 영업외수익, 강조: false },
      { 라벨: '영업외비용 (이자비용)', 금액: -영업외비용, 강조: false },
      { 라벨: '법인세차감전순이익', 금액: 법인세차감전순이익, 강조: true },
      { 라벨: '법인세비용', 금액: -법인세비용, 강조: false },
      { 라벨: '당기순이익', 금액: 당기순이익, 강조: true },
    ],
  };

  // ── 재무상태표 ────────────────────────────────
  const 자산항목 = 그룹(시산표, '자산');
  const 차감항목 = 그룹(시산표, '자산차감');
  const 부채항목 = 그룹(시산표, '부채');
  const 자본항목 = 그룹(시산표, '자본');

  const 자산총계 =
    자산항목.reduce((s, r) => s + r.금액, 0) - 차감항목.reduce((s, r) => s + r.금액, 0);
  const 부채총계 = 부채항목.reduce((s, r) => s + r.금액, 0);

  // 시산표의 이익잉여금은 기초 잔액 → 당기순이익을 더해야 기말 잔액
  const 이익잉여금기초 = 잔액(시산표, '402');
  const 이익잉여금기말 = 이익잉여금기초 + 당기순이익;
  const 자본금 = 잔액(시산표, '401');
  const 자본총계 = 자본금 + 이익잉여금기말;

  const 재무상태표 = {
    자산: { 항목: 자산항목, 차감: 차감항목, 총계: 자산총계 },
    부채: { 항목: 부채항목, 총계: 부채총계 },
    자본: {
      항목: [
        { 명: '자본금', 금액: 자본금 },
        { 명: '이익잉여금', 금액: 이익잉여금기말, 주석: `기초 ${이익잉여금기초.toLocaleString()} + 당기순이익 ${당기순이익.toLocaleString()}` },
      ],
      총계: 자본총계,
    },
    부채와자본총계: 부채총계 + 자본총계,
    // 시산표가 대차평형이면 이 등식은 자동으로 성립한다 (수학적 필연)
    대차일치: 자산총계 === 부채총계 + 자본총계,
  };

  // ── 이익잉여금처분계산서 ──────────────────────
  // ⚠️ 배당·적립은 사람의 의사결정(주총 결의). 데모에서는 무배당 가정.
  const 이익잉여금처분계산서 = {
    전기이월미처분이익잉여금: 이익잉여금기초,
    당기순이익,
    처분전이익잉여금: 이익잉여금기말,
    이익준비금적립: 0,
    배당금: 0,
    차기이월미처분이익잉여금: 이익잉여금기말,
    주석: '배당·적립 규모는 주주총회 결의 사항(비결정론 항목) — 데모는 무배당 가정',
  };

  return { 손익계산서, 재무상태표, 이익잉여금처분계산서 };
}
