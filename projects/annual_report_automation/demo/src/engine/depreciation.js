// 감가상각 계산 — 2단계(회계 계상)와 4단계(세법 시부인)가 공유하는 계산 요소
//
// ⚠️ 회계상 계상액과 세법상 상각범위액은 다른 개념이다.
//    2단계: 회사가 장부에 얼마를 적을 것인가 (회계)
//    4단계: 세법이 얼마까지 인정하는가 (시부인)
//    이 파일은 "상각률·월수" 같은 공통 요소만 제공하고, 판단은 각 단계가 한다.
//
// 근거: 법인세법 시행규칙 별표4(상각률표) · 별표5(기준내용연수)

/** 별표4 상각률표 — 정액법률 = 1/n, 정률법률 = 1 - 0.05^(1/n) */
export const 상각률표 = {
  4:  { 정액: 0.250, 정률: 0.528 },
  5:  { 정액: 0.200, 정률: 0.451 },
  6:  { 정액: 0.166, 정률: 0.394 },
  8:  { 정액: 0.125, 정률: 0.313 },
  10: { 정액: 0.100, 정률: 0.259 },
  20: { 정액: 0.050, 정률: 0.140 },
  40: { 정액: 0.025, 정률: null },  // 건축물은 정액법만
};

/** 기준내용연수 (별표5) 와 신고 가능 범위 (±25%) */
export const 기준내용연수 = {
  건축물: { 기준: 40, 범위: [30, 50] },
  차량운반구: { 기준: 5, 범위: [4, 6] },
  비품: { 기준: 5, 범위: [4, 6] },
};

/** 당기 사용 월수 (신규 취득 시 월할, 1개월 미만은 1개월) */
export function 사용월수(자산, 사업연도개시일, 사업연도종료일) {
  const 취득 = new Date(자산.취득일);
  const 개시 = new Date(사업연도개시일);
  const 종료 = new Date(사업연도종료일);
  if (취득 <= 개시) return 12;
  if (취득 > 종료) return 0;
  return 종료.getMonth() - 취득.getMonth() + 1;  // 취득한 달을 1개월로 산입
}

/**
 * 상각범위액 계산 (세법 공식 — 잔존가치를 빼지 않는다)
 *   정액법: 취득가액 × 정액법 상각률
 *   정률법: 미상각잔액(취득가액 - 기왕 상각누계) × 정률법 상각률
 */
export function 상각범위액(자산, { 방법, 내용연수 }, 회사) {
  const 월수 = 사용월수(자산, 회사.사업연도개시일, 회사.사업연도종료일);
  if (월수 === 0) return { 금액: 0, 산식: '당기 미사용', 월수 };

  const 률 = 상각률표[내용연수]?.[방법];
  if (률 == null) {
    throw new Error(`상각률 없음: ${내용연수}년 ${방법}법 (건축물은 정액법만 허용)`);
  }

  const 기준액 = 방법 === '정액' ? 자산.취득가 : 자산.취득가 - 자산.기초누계;
  const 기준액명 = 방법 === '정액' ? '취득가액' : '미상각잔액';
  const 연액 = Math.floor(기준액 * 률);
  const 금액 = Math.floor((연액 * 월수) / 12);

  return {
    금액, 월수, 률, 기준액,
    산식: `${기준액명} ${기준액.toLocaleString()} × ${방법}률 ${률}` +
          (월수 < 12 ? ` × ${월수}/12개월` : '') + ` = ${금액.toLocaleString()}`,
  };
}

/**
 * 자산의 당기 상각 선택값 결정.
 * 방법고정 자산(건축물·업무용승용차)은 선택을 무시하고 법정 방법을 강제한다.
 * → 절세 시나리오 엔진이 불법 조합을 생성하는 것 자체가 불가능해진다.
 */
export function 상각선택(자산, 사용자선택 = {}) {
  if (자산.방법고정) {
    return { 방법: 자산.방법, 내용연수: 자산.내용연수, 고정됨: true, 사유: 자산.비고 };
  }
  const 선택 = 사용자선택[자산.id] ?? {};
  return {
    방법: 선택.방법 ?? 자산.방법,
    내용연수: 선택.내용연수 ?? 자산.내용연수,
    고정됨: false,
  };
}
