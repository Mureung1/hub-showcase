// 절세 시나리오 엔진 — IDEA.md의 "경우의 수 계산 → 절세 방향 도출"
//
// 설계 원칙 두 가지:
//  ① 법적 제약을 코드로 강제한다 → 불법 조합은 생성 자체가 불가능하다.
//     (건축물=정액법만, 업무용승용차=5년 정액 강제, 기존 자산=계속적용 원칙으로 변경 불가)
//     → depreciation.js의 `상각선택()`이 방법고정 자산의 사용자 선택을 무시한다.
//  ② "추천"이 아니라 "적법 조합 비교표 + 근거"로 제시한다.
//     최종 판단은 세무사 — 세무대리 업역 리스크 회피.

import { 자산대장, 회사 } from '../data/mock.js';
import { 기준내용연수, 상각률표 } from './depreciation.js';
import { runPipeline } from './pipeline.js';

/** 선택 가능한 자산만 추출 — 방법고정 자산은 변수 공간에서 원천 배제된다 */
export function 결정변수() {
  return 자산대장.map((a) => {
    if (a.방법고정) {
      return {
        자산id: a.id, 자산: a.명, 선택가능: false,
        고정값: { 방법: a.방법, 내용연수: a.내용연수 },
        사유: a.비고,
      };
    }
    const 범위 = 기준내용연수[a.구분]?.범위 ?? [a.내용연수, a.내용연수];
    const 연수후보 = Object.keys(상각률표).map(Number)
      .filter((n) => n >= 범위[0] && n <= 범위[1]);
    return {
      자산id: a.id, 자산: a.명, 선택가능: true,
      방법후보: ['정액', '정률'],
      연수후보,
      기준: { 방법: a.방법, 내용연수: a.내용연수 },
      사유: a.비고,
    };
  });
}

/** 적법 조합 전개 → 각각 파이프라인 실행 → 세액 비교 */
export function runScenarios() {
  const 변수 = 결정변수();
  const 대상 = 변수.filter((v) => v.선택가능);

  // 데모에서는 선택 가능한 자산이 1개(비품)이므로 단순 전개.
  // 자산이 늘면 데카르트 곱으로 확장된다.
  const 조합 = [];
  for (const v of 대상) {
    for (const 방법 of v.방법후보) {
      for (const 내용연수 of v.연수후보) {
        조합.push({ [v.자산id]: { 방법, 내용연수 } });
      }
    }
  }

  const 기준선택 = Object.fromEntries(대상.map((v) => [v.자산id, v.기준]));
  const 기준결과 = runPipeline({ 사용자선택: 기준선택 });
  const 기준세액 = 기준결과.stage5.총납부액;

  const 결과 = 조합.map((사용자선택) => {
    const r = runPipeline({ 사용자선택 });
    const [자산id, 선택] = Object.entries(사용자선택)[0];
    const 자산 = 자산대장.find((a) => a.id === 자산id);
    const 상각비 = r.stage2.감가.find((d) => d.자산id === 자산id);

    return {
      조합: `${선택.방법}법 · ${선택.내용연수}년`,
      방법: 선택.방법, 내용연수: 선택.내용연수,
      당기상각비: 상각비.금액,
      산식: 상각비.산식,
      과세표준: r.stage4.별지3.과세표준,
      법인세: r.stage4.별지3.산출세액,
      지방소득세: r.stage4.지방소득세.산출세액,
      총납부액: r.stage5.총납부액,
      기준대비: r.stage5.총납부액 - 기준세액,
      기준여부: 선택.방법 === 자산.방법 && 선택.내용연수 === 자산.내용연수,
      근거: `법인세법 시행령 §26(상각방법 선택) · 시행규칙 §15(내용연수 ±25% 신고)`,
    };
  }).sort((a, b) => a.총납부액 - b.총납부액);

  const 최소 = 결과[0];
  const 최대 = 결과[결과.length - 1];
  const 자산 = 자산대장.find((a) => a.id === 대상[0]?.자산id);

  return {
    변수, 결과, 기준세액,
    최소세액조합: 최소, 최대세액조합: 최대,
    최대절감액: 최대.총납부액 - 최소.총납부액,

    경고: [
      {
        유형: '과세이연',
        내용: `상각방법·내용연수 선택은 **절대 절감이 아니라 과세이연**입니다. ` +
              `${자산?.명 ?? '해당 자산'}의 취득가 ${(자산?.취득가 ?? 0).toLocaleString()}원은 ` +
              `어느 방법을 택하든 내용연수에 걸쳐 전액 손금이 됩니다. ` +
              `올해 많이 상각하면 내년 이후 상각비가 줄어 세금이 늘어납니다. ` +
              `유리한 것은 "돈을 늦게 내는 것"(화폐의 시간가치)이지 "덜 내는 것"이 아닙니다.`,
      },
      {
        유형: '계속적용',
        내용: '한 번 신고한 상각방법·내용연수는 계속 적용이 원칙입니다(변경은 관할세무서장 승인 필요). ' +
              '올해의 선택이 내년 이후를 구속하므로, 단년도 세액만 보고 결정하면 안 됩니다.',
      },
      {
        유형: '판단 주체',
        내용: '이 표는 **적법한 선택지의 비교**이지 추천이 아닙니다. ' +
              '실제 적용은 세무사와 상의해 결정하시고, 최종 조정계산서는 세무사 검토·서명을 거쳐야 합니다.',
      },
    ],

    배제된변수: 변수.filter((v) => !v.선택가능).map((v) => ({
      자산: v.자산, 고정값: `${v.고정값.방법}법 · ${v.고정값.내용연수}년`, 사유: v.사유,
    })),
  };
}

/**
 * ★ 1단계 분개 판정 하나가 세금을 얼마나 가르는가 — 이 프로젝트의 존재 이유를 보여주는 계산.
 * 임차인C의 1,000만원을 임대보증금(정답)으로 볼 때 vs 임대료수입(오분개)으로 볼 때.
 */
export function 분개영향() {
  const 정답 = runPipeline({ 큐답변: { Q1: '임대보증금' } });
  const 오답 = runPipeline({ 큐답변: { Q1: '임대료수입' } });

  return {
    질문: '통장의 "임차인C 10,000,000 입금" 한 줄을 어떻게 판정하는가',
    케이스: [
      {
        판정: '임대보증금 (부채)', 정답: true,
        당기순이익: 정답.stage3.손익계산서.당기순이익,
        과세표준: 정답.stage4.별지3.과세표준,
        총납부액: 정답.stage5.총납부액,
        해설: '나중에 돌려줄 돈 → 부채. 수익이 아니므로 소득에 영향 없음.',
      },
      {
        판정: '임대료수입 (수익)', 정답: false,
        당기순이익: 오답.stage3.손익계산서.당기순이익,
        과세표준: 오답.stage4.별지3.과세표준,
        총납부액: 오답.stage5.총납부액,
        해설: '⚠️ 오분개. 부채를 수익으로 잡아 소득 1,000만원 과대계상.',
      },
    ],
    세액차이: 오답.stage5.총납부액 - 정답.stage5.총납부액,
    결론: '통장 한 줄의 계정과목 판정이 세금을 직접 가른다. ' +
          '자료를 "가져오는" 일에는 이미 사람이 없다 — 가져온 자료를 "판정하는" 일에 사람이 있고, ' +
          '이것이 AI가 대체할 지점이다.',
  };
}
