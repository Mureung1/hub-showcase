"""별지3 세액 계산 검증.
세율표는 법인세법 §55(2025 개편본), 계산 구조는 §13. 손계산으로 기댓값을 검산했다.
"""

import unittest
from decimal import Decimal

from taxengine.engine.tax import 누진세액, 계산
from taxengine.domain.rates import 법인세율

D = Decimal


class 누진세액_테스트(unittest.TestCase):
    def test_2억이하_단일구간_9퍼센트(self):
        self.assertEqual(누진세액(D(100_000_000), 법인세율("2025-01-01"))["세액"], D(9_000_000))

    def test_3억은_2억9퍼_더하기_1억19퍼(self):
        self.assertEqual(누진세액(D(300_000_000), 법인세율("2025-01-01"))["세액"],
                         D(18_000_000) + D(19_000_000))

    def test_2026개시는_1퍼센트p_인상_2억이하_10퍼센트(self):
        self.assertEqual(누진세액(D(100_000_000), 법인세율("2026-01-01"))["세액"], D(10_000_000))

    def test_과세표준_0이면_세액_0(self):
        self.assertEqual(누진세액(D(0), 법인세율("2025-01-01"))["세액"], D(0))


class 별지3_테스트(unittest.TestCase):
    def test_당기순이익_조정_각사업연도소득(self):
        r = 계산({"당기순이익": 80_000_000, "가산조정": 15_000_000, "차감조정": 5_000_000,
                 "사업연도개시일": "2025-01-01", "중소기업": True})
        self.assertEqual(r["각사업연도소득"], D(90_000_000))
        self.assertEqual(r["과세표준"], D(90_000_000))
        self.assertEqual(r["산출세액"], D(90_000_000) * D("0.09"))

    def test_차감납부세액_공식(self):
        # 중소기업으로 고정 — 일반법인은 2025년 세율(9%)이 최저한세율(10%)보다 낮아
        # 이 브래킷에서 공제감면이 전부 배제되므로(§test_amt.py), 이 테스트의 의도(단순 뺄셈 공식
        # 검증)와 최저한세 상호작용이 섞이지 않도록 분리한다.
        r = 계산({"당기순이익": 100_000_000, "사업연도개시일": "2025-01-01", "중소기업": True,
                 "공제감면세액": 1_500_000, "가산세": 200_000, "기납부세액": 3_000_000})
        self.assertEqual(r["차감납부세액"], r["산출세액"] - D(1_500_000) + D(200_000) - D(3_000_000))

    def test_이월결손금_중소기업_100퍼센트_공제(self):
        r = 계산({"당기순이익": 100_000_000, "이월결손금": 100_000_000,
                 "중소기업": True, "사업연도개시일": "2025-01-01"})
        self.assertEqual(r["이월결손금공제"], D(100_000_000))
        self.assertEqual(r["과세표준"], D(0))

    def test_이월결손금_일반법인_80퍼센트_한도(self):
        r = 계산({"당기순이익": 100_000_000, "이월결손금": 100_000_000,
                 "중소기업": False, "사업연도개시일": "2025-01-01"})
        self.assertEqual(r["이월결손금공제"], D(80_000_000))
        self.assertEqual(r["과세표준"], D(20_000_000))

    def test_기부금_한도초과는_별지3에서_직접_가산(self):
        기본 = 계산({"당기순이익": 100_000_000, "사업연도개시일": "2025-01-01"})
        기부 = 계산({"당기순이익": 100_000_000, "기부금한도초과": 10_000_000, "사업연도개시일": "2025-01-01"})
        self.assertEqual(기부["각사업연도소득"] - 기본["각사업연도소득"], D(10_000_000))

    def test_지방소득세_독립세율_2억이하_0점9퍼센트(self):
        r = 계산({"당기순이익": 100_000_000, "사업연도개시일": "2025-01-01"})
        self.assertEqual(r["지방소득세"]["산출세액"], D(100_000_000) * D("0.009"))

    def test_단계배열_마지막은_차감납부세액(self):
        r = 계산({"당기순이익": 100_000_000, "사업연도개시일": "2025-01-01", "기납부세액": 1_000_000})
        최종 = r["단계"][-1]
        self.assertTrue(최종["최종"])
        self.assertEqual(최종["금액"], r["차감납부세액"])


if __name__ == "__main__":
    unittest.main()
