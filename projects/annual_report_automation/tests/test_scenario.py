import unittest
from decimal import Decimal

from taxengine.engine import scenario as S

D = Decimal

회사 = {"사업연도개시일": "2025-01-01", "사업연도종료일": "2025-12-31"}


def 비품(회사계상액=2_000_000):
    return {"명": "비품A", "구분": "비품", "취득일": "2024-01-01", "취득가": D(10_000_000),
            "기초누계": D(0), "회사계상액": D(회사계상액), "방법": "정액", "내용연수": 5,
            "전기이월부인액": D(0), "업무용승용차": False}


def 건물():
    return {"명": "건물A", "구분": "건축물", "취득일": "2020-01-01", "취득가": D(100_000_000),
            "기초누계": D(10_000_000), "회사계상액": D(2_500_000), "방법": "정액", "내용연수": 40,
            "전기이월부인액": D(0), "업무용승용차": False}


def 승용차():
    return {"명": "차A", "구분": "차량운반구", "취득일": "2024-01-01", "취득가": D(50_000_000),
            "기초누계": D(0), "회사계상액": D(10_000_000), "방법": "정액", "내용연수": 5,
            "전기이월부인액": D(0), "업무용승용차": True}


class 자산별_선택지_테스트(unittest.TestCase):
    def test_건축물은_방법이_고정돼_선택지가_1개(self):
        self.assertEqual(S.자산별_선택지(건물()), [{"방법": "정액", "내용연수": 40}])

    def test_업무용승용차는_5년정액_1개로_고정(self):
        self.assertEqual(S.자산별_선택지(승용차()), [{"방법": "정액", "내용연수": 5}])

    def test_비품은_방법X내용연수_조합이_여러개(self):
        선택지 = S.자산별_선택지(비품())
        # 비품 범위 4~6년, 상각률표에 4/5/6년 모두 정액·정률 존재 → 2×3=6
        self.assertEqual(len(선택지), 6)
        self.assertIn({"방법": "정률", "내용연수": 6}, 선택지)


class 비교_테스트(unittest.TestCase):
    입력공통 = {"당기순이익": D(100_000_000), "중소기업": True, "사업연도개시일": "2025-01-01"}

    def test_조합_개수는_선택지_곱(self):
        r = S.비교([비품()], 회사, 0, 0, self.입력공통)
        self.assertEqual(len(r["조합들"]), 6)

    def test_고정자산만_있으면_조합_1개(self):
        r = S.비교([건물(), 승용차()], 회사, 0, 0, self.입력공통)
        self.assertEqual(len(r["조합들"]), 1)

    def test_차감납부세액_오름차순_정렬(self):
        r = S.비교([비품()], 회사, 0, 0, self.입력공통)
        세액들 = [c["차감납부세액"] for c in r["조합들"]]
        self.assertEqual(세액들, sorted(세액들))
        self.assertEqual(r["최선"], r["조합들"][0])
        self.assertEqual(r["최다부담"], r["조합들"][-1])

    def test_정률법_선택시_회사계상액_대비_한도가_달라져_부인_추인이_갈린다(self):
        r = S.비교([비품(회사계상액=2_000_000)], 회사, 0, 0, self.입력공통)
        # 회사계상액 200만은 고정 — 방법/연수에 따라 상각범위액이 바뀌며 부인/추인이 달라진다
        조합별 = {(c["선택"][0]["방법"], c["선택"][0]["내용연수"]): c for c in r["조합들"]}
        정액4년 = 조합별[("정액", 4)]  # 범위 = 1000만×0.25=250만 > 계상 200만 → 시인부족(추인 가능하나 전기이월 없어 0)
        self.assertEqual(정액4년["감가부인"], D(0))

    def test_과세이연_경고가_항상_붙는다(self):
        r = S.비교([비품()], 회사, 0, 0, self.입력공통)
        self.assertIn("과세이연", r["과세이연_경고"])

    def test_조합수_상한_넘으면_에러(self):
        with self.assertRaises(ValueError):
            S.비교([비품(), 비품()], 회사, 0, 0, self.입력공통, 최대조합수=10)


if __name__ == "__main__":
    unittest.main()
