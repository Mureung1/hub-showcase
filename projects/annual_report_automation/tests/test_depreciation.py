"""감가상각 엔진 검증.

⚠️ 여기 기댓값은 내가 지어낸 게 아니라 세법이 정한 값이다 (research.md §5 교과서 예제).
   상각률표는 법인세법 시행규칙 별표4에서 왔다. 순환논증이 아니다.
"""

import unittest
from decimal import Decimal

from taxengine.engine.depreciation import 사용월수, 상각선택, 상각범위액, 시부인

FY2025 = {"사업연도개시일": "2025-01-01", "사업연도종료일": "2025-12-31"}
D = Decimal


class 상각범위액_교과서예제(unittest.TestCase):
    def test_기계장치_1억_5년_정률법_1년차(self):
        # 별표4 상각률 0.451 → 45,100,000
        자산 = {"취득일": "2020-01-01", "취득가": 100_000_000, "기초누계": 0}
        self.assertEqual(상각범위액(자산, {"방법": "정률", "내용연수": 5}, FY2025)["금액"], D(45_100_000))

    def test_기계장치_1억_5년_정액법(self):
        자산 = {"취득일": "2020-01-01", "취득가": 100_000_000, "기초누계": 0}
        self.assertEqual(상각범위액(자산, {"방법": "정액", "내용연수": 5}, FY2025)["금액"], D(20_000_000))

    def test_정률법_2년차는_미상각잔액_기준(self):
        자산 = {"취득일": "2020-01-01", "취득가": 100_000_000, "기초누계": 45_100_000}
        # (1억 − 4510만) × 0.451 = 24,759,900
        self.assertEqual(상각범위액(자산, {"방법": "정률", "내용연수": 5}, FY2025)["금액"], D(24_759_900))


class 월할(unittest.TestCase):
    def test_7월취득_신규자산은_6개월(self):
        자산 = {"취득일": "2025-07-10", "취득가": 100_000_000, "기초누계": 0}
        r = 상각범위액(자산, {"방법": "정액", "내용연수": 5}, FY2025)
        self.assertEqual(r["월수"], 6)
        self.assertEqual(r["금액"], D(10_000_000))

    def test_취득한_달을_1개월로_산입(self):
        self.assertEqual(사용월수("2025-12-20", "2025-01-01", "2025-12-31"), 1)

    def test_사업연도_개시전_취득은_12개월(self):
        self.assertEqual(사용월수("2019-05-01", "2025-01-01", "2025-12-31"), 12)


class 법적제약_강제(unittest.TestCase):
    def test_건축물에_정률법_지정해도_정액법_강제(self):
        선택 = 상각선택({"구분": "건축물", "방법": "정액", "내용연수": 40}, {"방법": "정률", "내용연수": 20})
        self.assertEqual(선택["방법"], "정액")
        self.assertTrue(선택["고정"])

    def test_건축물_40년_정률률은_없어_에러(self):
        자산 = {"취득일": "2015-01-01", "취득가": 500_000_000, "기초누계": 0}
        with self.assertRaises(ValueError):
            상각범위액(자산, {"방법": "정률", "내용연수": 40}, FY2025)

    def test_업무용승용차는_5년_정액_강제(self):
        선택 = 상각선택({"구분": "차량운반구", "방법": "정률", "내용연수": 4, "업무용승용차": True})
        self.assertEqual(선택["방법"], "정액")
        self.assertEqual(선택["내용연수"], 5)


class 시부인_판정(unittest.TestCase):
    def test_계상액_초과하면_부인액_손금불산입(self):
        자산 = {"명": "기계", "취득일": "2020-01-01", "취득가": 100_000_000, "기초누계": 0,
                "방법": "정액", "내용연수": 5, "회사계상액": 25_000_000}
        r = 시부인(자산, FY2025)
        self.assertEqual(r["상각범위액"], D(20_000_000))
        self.assertEqual(r["부인액"], D(5_000_000))
        self.assertEqual(r["추인액"], D(0))

    def test_시인부족_전기부인_있으면_한도내_추인(self):
        자산 = {"명": "기계", "취득일": "2020-01-01", "취득가": 100_000_000, "기초누계": 0,
                "방법": "정액", "내용연수": 5, "회사계상액": 15_000_000, "전기이월부인액": 8_000_000}
        r = 시부인(자산, FY2025)
        self.assertEqual(r["부인액"], D(0))
        self.assertEqual(r["추인액"], D(5_000_000))  # min(부족 500만, 전기부인 800만)

    def test_시인부족_전기부인_없으면_소멸(self):
        자산 = {"명": "기계", "취득일": "2020-01-01", "취득가": 100_000_000, "기초누계": 0,
                "방법": "정액", "내용연수": 5, "회사계상액": 15_000_000}
        self.assertEqual(시부인(자산, FY2025)["추인액"], D(0))


if __name__ == "__main__":
    unittest.main()
