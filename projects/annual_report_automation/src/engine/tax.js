// 별지 제3호 — 법인세 과세표준 및 세액조정계산서
//
// research.md §1 "법인세 계산 구조"를 그대로 옮긴 세액 계산의 본체.
// 근거: 법인세법 §13(과세표준), §55(세율), §13①(이월결손금)

import { 법인세율, 지방소득세율, 이월결손금공제율 } from '../domain/rates.js';

/**
 * 누진 구간 합산. 과세표준을 구간별로 쪼개 각 세율을 적용한다.
 * @returns {{ 세액:number, 내역:{구간,금액,율,세액}[] }}
 */
export function 누진세액(과세표준, 세율표) {
  let 이전상한 = 0, 세액 = 0;
  const 내역 = [];
  for (const 구간 of 세율표) {
    const 구간액 = Math.max(0, Math.min(과세표준, 구간.상한) - 이전상한);
    if (구간액 > 0) {
      const 부분 = Math.floor(구간액 * 구간.율);
      세액 += 부분;
      내역.push({ 구간: 구간.구간 ?? '', 금액: 구간액, 율: 구간.율, 세액: 부분 });
    }
    이전상한 = 구간.상한;
    if (과세표준 <= 구간.상한) break;
  }
  return { 세액, 내역 };
}

/**
 * 별지3 세액 계산.
 * @param {object} 입력
 *   당기순이익      : 손익계산서 (3단계)
 *   가산조정        : 익금산입·손금불산입 합계 (소득금액조정합계표 좌측)
 *   차감조정        : 손금산입·익금불산입 합계 (우측)
 *   기부금한도초과  : 별지3에서 직접 가산 (합계표에 안 들어감)
 *   이월결손금      : 전기 (갑)표에서 온 잔액
 *   비과세소득, 소득공제
 *   공제감면세액, 가산세, 기납부세액
 *   중소기업        : 이월결손금 공제한도 스위치
 *   사업연도개시일  : 세율표 선택
 */
export function 계산(입력) {
  const {
    당기순이익, 가산조정 = 0, 차감조정 = 0, 기부금한도초과 = 0,
    이월결손금 = 0, 비과세소득 = 0, 소득공제 = 0,
    공제감면세액 = 0, 가산세 = 0, 기납부세액 = 0,
    중소기업 = false, 사업연도개시일,
  } = 입력;

  const 각사업연도소득 = 당기순이익 + 가산조정 - 차감조정 + 기부금한도초과;

  // 이월결손금 공제한도: 중소기업 100%, 일반 80%
  const 공제율 = 중소기업 ? 이월결손금공제율.중소 : 이월결손금공제율.일반;
  const 이월결손금공제 = Math.min(이월결손금, Math.floor(Math.max(0, 각사업연도소득) * 공제율));

  const 과세표준 = Math.max(0, 각사업연도소득 - 이월결손금공제 - 비과세소득 - 소득공제);

  const 법인 = 누진세액(과세표준, 법인세율(사업연도개시일));
  const 산출세액 = 법인.세액;

  // 공제·감면 (최저한세 적용 후) → 이 엔진은 감면액을 입력으로 받음. 최저한세 로직은 후속 모듈.
  const 차감납부세액 = 산출세액 - 공제감면세액 + 가산세 - 기납부세액;

  // 지방소득세: 같은 과세표준에 독립세율 (위택스 별도 신고)
  const 지방 = 누진세액(과세표준, 지방소득세율(사업연도개시일));

  return {
    각사업연도소득, 이월결손금공제, 과세표준,
    산출세액, 세율내역: 법인.내역,
    공제감면세액, 가산세, 기납부세액,
    차감납부세액,
    지방소득세: { 과세표준, 산출세액: 지방.세액, 내역: 지방.내역 },
    총납부세액: 차감납부세액 + 지방.세액,
    // 별지3 표시용 단계
    단계: [
      { 부호: '',  라벨: '결산서상 당기순이익', 금액: 당기순이익 },
      { 부호: '+', 라벨: '익금산입·손금불산입', 금액: 가산조정 },
      { 부호: '−', 라벨: '손금산입·익금불산입', 금액: 차감조정 },
      ...(기부금한도초과 ? [{ 부호: '+', 라벨: '기부금 한도초과', 금액: 기부금한도초과 }] : []),
      { 부호: '=', 라벨: '각 사업연도 소득금액', 금액: 각사업연도소득, 강조: true },
      { 부호: '−', 라벨: `이월결손금 공제 (${중소기업 ? '중소 100%' : '일반 80%'} 한도)`, 금액: 이월결손금공제 },
      { 부호: '=', 라벨: '과세표준', 금액: 과세표준, 강조: true },
      { 부호: '×', 라벨: '세율', 금액: null, 주석: 법인.내역.map((b) => `${b.구간} ${(b.율 * 100).toFixed(0)}%`).join(' / ') },
      { 부호: '=', 라벨: '산출세액', 금액: 산출세액, 강조: true },
      ...(공제감면세액 ? [{ 부호: '−', 라벨: '공제·감면세액', 금액: 공제감면세액 }] : []),
      ...(가산세 ? [{ 부호: '+', 라벨: '가산세', 금액: 가산세 }] : []),
      { 부호: '−', 라벨: '기납부세액', 금액: 기납부세액 },
      { 부호: '=', 라벨: '차감 납부할 세액', 금액: 차감납부세액, 강조: true, 최종: true },
    ],
  };
}
