// 감가상각 엔진 — 세법상 상각범위액 계산 + 시부인
//
// ⚠️ 두 개념을 절대 혼동하지 않는다:
//   · 상각범위액 = 세법이 허용하는 그 해의 최대 손금 (이 파일이 계산)
//   · 회사계상액 = 회사가 장부에 실제로 적은 감가상각비 (입력으로 받음)
//   시부인 = 둘의 비교. 초과분은 손금불산입(유보), 부족분은 전기 부인액 한도 내 추인.
//
// 근거: 법인세법 §23, 시행령 §26, 시행규칙 §15 · research.md §5

import { 상각률표, 기준내용연수 } from '../domain/rates.js';

/**
 * 당기 사용 월수 (신규 취득 시 월할, 1개월 미만은 1개월로 산입).
 * 근거: 법인세법 시행령 §26⑨
 */
export function 사용월수(취득일, 개시일, 종료일) {
  const 취득 = new Date(취득일), 개시 = new Date(개시일), 종료 = new Date(종료일);
  if (취득 <= 개시) return 12;
  if (취득 > 종료) return 0;
  return (종료.getFullYear() - 취득.getFullYear()) * 12
       + (종료.getMonth() - 취득.getMonth()) + 1; // 취득한 달을 1개월로
}

/**
 * 상각방법·내용연수 결정. 방법고정 자산(건축물·업무용승용차)은 선택을 무시하고 법정값 강제.
 * → 절세 시나리오가 불법 조합(건물 정률 등)을 만드는 것 자체가 불가능해진다.
 * @param {object} 자산  { 구분, 방법, 내용연수, 업무용승용차? }
 * @param {object} 선택  { 방법?, 내용연수? } 사용자/시나리오 지정 (선택)
 */
export function 상각선택(자산, 선택 = {}) {
  // 업무용승용차: 2016.1.1 이후 취득분은 5년 정액법 강제 (법인세법 §27의2)
  if (자산.업무용승용차) {
    return { 방법: '정액', 내용연수: 5, 고정: true, 사유: '업무용승용차 5년 정액 강제(§27의2)' };
  }
  // 건축물: 정액법만 허용 (시행령 §26)
  const 고정방법 = 기준내용연수[자산.구분]?.방법고정;
  if (고정방법) {
    return { 방법: 고정방법, 내용연수: 선택.내용연수 ?? 자산.내용연수, 고정: true,
             사유: `${자산.구분}은 ${고정방법}법만 허용(시행령 §26)` };
  }
  return { 방법: 선택.방법 ?? 자산.방법, 내용연수: 선택.내용연수 ?? 자산.내용연수, 고정: false };
}

/**
 * 세법상 상각범위액 (세법 공식은 잔존가치를 빼지 않는다).
 *   정액법: 취득가액 × 정액률
 *   정률법: 미상각잔액(취득가액 − 기왕 상각누계) × 정률률
 * @returns {{ 금액:number, 월수:number, 율:number, 기준액:number, 산식:string }}
 */
export function 상각범위액(자산, 선택, 회사) {
  const 월수 = 사용월수(자산.취득일, 회사.사업연도개시일, 회사.사업연도종료일);
  if (월수 === 0) return { 금액: 0, 월수, 율: 0, 기준액: 0, 산식: '당기 미사용' };

  const 율 = 상각률표[선택.내용연수]?.[선택.방법];
  if (율 == null) {
    throw new Error(
      `상각률 없음: 내용연수 ${선택.내용연수}년 · ${선택.방법}법 ` +
      `(건축물 40년은 정액법만 허용)`,
    );
  }

  const 정률 = 선택.방법 === '정률';
  const 기준액 = 정률 ? 자산.취득가 - (자산.기초누계 ?? 0) : 자산.취득가;
  const 연액 = Math.floor(기준액 * 율);
  const 금액 = Math.floor((연액 * 월수) / 12);

  return {
    금액, 월수, 율, 기준액,
    산식: `${정률 ? '미상각잔액' : '취득가액'} ${기준액.toLocaleString()} × ${선택.방법}률 ${율}`
        + (월수 < 12 ? ` × ${월수}/12개월` : '') + ` = ${금액.toLocaleString()}`,
  };
}

/**
 * 시부인 — 회사계상액과 상각범위액을 비교해 세무조정을 산출한다. 자산별 계산(통산 금지).
 * @param {object} 자산 { 명, 구분, 취득가, 기초누계, 회사계상액, 전기이월부인액?, 방법, 내용연수, 업무용승용차? }
 * @returns {{ 부인액, 추인액, 상각범위액, 회사계상액, 방법, 내용연수, 판정, 산식 }}
 */
export function 시부인(자산, 회사, 선택지정 = {}) {
  const 선택 = 상각선택(자산, 선택지정);
  const 범위 = 상각범위액(자산, 선택, 회사);
  const 계상 = 자산.회사계상액 ?? 범위.금액;
  const 전기부인 = 자산.전기이월부인액 ?? 0;
  const 차이 = 계상 - 범위.금액;

  let 부인액 = 0, 추인액 = 0, 판정;
  if (차이 > 0) {
    부인액 = 차이;                    // 손금불산입(유보)
    판정 = '상각부인 → 손금불산입(유보)';
  } else if (차이 < 0) {
    추인액 = Math.min(-차이, 전기부인); // 시인부족액 한도 내에서 전기 부인액 추인(△유보)
    판정 = 추인액 > 0 ? '시인부족 → 전기부인액 손금추인(△유보)' : '시인부족 → 소멸';
  } else {
    판정 = '일치';
  }

  return {
    자산: 자산.명, 방법: 선택.방법, 내용연수: 선택.내용연수, 방법고정: 선택.고정,
    회사계상액: 계상, 상각범위액: 범위.금액, 산식: 범위.산식,
    부인액, 추인액, 판정,
  };
}
