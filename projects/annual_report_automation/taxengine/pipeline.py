"""파이프라인 — 사업연도 폴더 하나를 받아 세무조정 전 과정을 실행한다 (출력 없음).

reproduce.py(화면 출력)와 carryover.py(연도 간 이월)가 공유하는 순수 계산부.
"""

from decimal import Decimal

from taxengine.loader import 로드, 자산행, 차량행, 합계
from taxengine.validate import 검증
from taxengine.engine.depreciation import 시부인
from taxengine.engine.tax import 계산
from taxengine.engine import entertainment as 추진비엔진
from taxengine.engine import car as 승용차엔진
from taxengine.domain.period import 사업연도월수
from taxengine.domain.company import 소규모임대법인여부


def 실행(d) -> dict:
    """폴더 d의 종이책 데이터로 세무조정을 계산해 결과 묶음을 돌려준다.

    반환: {회사, v(검증), 시부인들, 감가부인, 감가추인, 가산조정, 차감조정, r(별지3), 자산대장, 정답}
    """
    data = 로드(d)
    회사, 손익계산서, 재무상태표 = data["회사"], data["손익계산서"], data["재무상태표"]
    자산대장, 조정, 정답 = data["자산대장"], data["조정"], data["정답"]
    차량대장 = data["차량대장"]

    v = 검증(재무상태표=재무상태표, 손익계산서=손익계산서, 자산대장=자산대장)

    시부인들 = [시부인(자산행(a), 회사) for a in 자산대장]
    감가부인 = sum((s["부인액"] for s in 시부인들), Decimal(0))
    감가추인 = sum((s["추인액"] for s in 시부인들), Decimal(0))

    소규모임대법인 = 소규모임대법인여부(회사)

    # 기업업무추진비 한도 자동계산 — company.csv에 수입금액이 있을 때만 (하위호환:
    # 없으면 예전처럼 adjustments.csv에 사람이 직접 최종 금액을 적는 방식 그대로 둔다)
    추진비 = None
    if 회사.get("수입금액") is not None:
        월수 = 사업연도월수(회사["사업연도개시일"], 회사["사업연도종료일"])
        추진비계상액 = 합계([r for r in 손익계산서 if r.get("계정") == "기업업무추진비"], "금액")
        한도결과 = 추진비엔진.한도(회사["수입금액"], 월수, 회사.get("중소기업") is True, 소규모임대법인)
        추진비 = 추진비엔진.시부인(추진비계상액, 회사.get("기업업무추진비_증빙불비금액", 0), 한도결과)

    # 업무용승용차 한도 자동계산 — cars.csv가 있을 때만 (하위호환: 없으면 계산 자체를 생략)
    차량판정들 = [승용차엔진.판정(차량행(c), 소규모임대법인) for c in 차량대장]
    차량손금불산입 = sum((c["손금불산입액"] for c in 차량판정들), Decimal(0))

    가산조정 = 합계([r for r in 조정 if r["구분"] in ("익금산입", "손금불산입")], "금액") + 감가부인
    if 추진비:
        가산조정 += 추진비["손금불산입합계"]
    가산조정 += 차량손금불산입
    차감조정 = 합계([r for r in 조정 if r["구분"] in ("손금산입", "익금불산입")], "금액") + 감가추인

    r = 계산({
        "당기순이익": v["당기순이익"], "가산조정": 가산조정, "차감조정": 차감조정,
        "기부금한도초과": 회사.get("기부금한도초과", 0), "이월결손금": 회사.get("이월결손금", 0),
        "공제감면세액": 회사.get("공제감면세액", 0), "가산세": 회사.get("가산세", 0),
        "기납부세액": 회사.get("기납부세액", 0),
        "중소기업": 회사.get("중소기업") is True, "사업연도개시일": 회사["사업연도개시일"],
    })

    return {
        "회사": 회사, "v": v, "시부인들": 시부인들,
        "감가부인": 감가부인, "감가추인": 감가추인,
        "추진비": 추진비, "차량판정들": 차량판정들, "차량손금불산입": 차량손금불산입,
        "가산조정": 가산조정, "차감조정": 차감조정,
        "r": r, "자산대장": 자산대장, "차량대장": 차량대장, "정답": 정답,
    }
