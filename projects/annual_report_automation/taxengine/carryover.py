"""연도 간 자동이월 — 전기(작년) 결과가 당기(올해) 기초값이 되는 흐름을 계산·검증한다.

두 해 책자(예: 2024·2025)가 있을 때, "2024가 2025로 정확히 흘러가는가"를 본다.
한 해만 맞추는 건 우연일 수 있지만, 두 해가 연결되면 우연이 아니다.

이월되는 값 3가지:
  · 감가상각 누계액   : 전기 기초누계 + 전기 회사계상액  → 당기 기초누계
  · 감가상각 유보     : 전기 전기이월부인액 + 전기 부인액 − 전기 추인액  → 당기 전기이월부인액
  · 이월결손금       : 전기 이월결손금 잔액(− 당기공제) + 당기 발생결손

근거: 자본금과적립금조정명세서(을)의 유보 누적 관리 (research.md §3-13)
"""

from decimal import Decimal

from taxengine.money import 원
from taxengine.loader import 자산행
from taxengine.engine.depreciation import 시부인


def 자산이월(전기자산: dict, 전기회사: dict) -> dict:
    """전기 자산 1건 → 당기 기초값(기초누계·전기이월부인액)을 계산."""
    a = 자산행(전기자산)
    s = 시부인(a, 전기회사)
    return {
        "명": a["명"],
        # 당기 기초누계 = 전기 기초누계 + 전기에 실제 계상한 상각비
        "기초누계": 원(a.get("기초누계", 0)) + s["회사계상액"],
        # 당기 전기이월부인액 = 전기 이월부인 + 전기 부인 − 전기 추인 (유보 누적)
        "전기이월부인액": 원(a.get("전기이월부인액", 0)) + s["부인액"] - s["추인액"],
    }


def 이월결손금이월(전기결과: dict, 전기회사: dict) -> Decimal:
    """전기 미공제 이월결손금 잔액 + 당기 발생결손 = 당기로 넘어갈 이월결손금."""
    잔여 = 원(전기회사.get("이월결손금", 0)) - 전기결과["r"]["이월결손금공제"]
    발생 = max(Decimal(0), -전기결과["r"]["각사업연도소득"])  # 각소득이 (−)면 결손 발생
    return max(Decimal(0), 잔여) + 발생


def 연속성검증(전기결과: dict, 당기_자산대장: list, 당기_회사: dict) -> dict:
    """전기가 함의하는 당기 기초값과, 당기 입력값이 일치하는지 검증한다.

    불일치 = 두 책자 사이 입력 오류(연도 밀림·오타·이월 누락)의 신호.
    반환: {'ok': bool, 'checks': [{'name','ok','detail'}]}
    """
    checks = []

    def add(name, ok, detail):
        checks.append({"name": name, "ok": ok, "detail": detail})

    전기회사 = 전기결과["회사"]
    기대 = {v["명"]: v for v in (자산이월(a, 전기회사) for a in 전기결과["자산대장"])}
    당기 = {a["명"]: a for a in 당기_자산대장}

    # 1. 자산별 기초누계·전기이월부인액 대조
    for 명, exp in 기대.items():
        cur = 당기.get(명)
        if cur is None:
            add(f"[{명}] 당기 자산대장에 존재", False, "전기에 있던 자산이 당기에 없음")
            continue
        누계_ok = 원(cur.get("기초누계", 0)) == exp["기초누계"]
        add(f"[{명}] 기초누계 이월", 누계_ok,
            f"기대 {int(exp['기초누계']):,} / 입력 {int(원(cur.get('기초누계', 0))):,}")
        부인_ok = 원(cur.get("전기이월부인액", 0)) == exp["전기이월부인액"]
        add(f"[{명}] 전기이월부인액(유보) 이월", 부인_ok,
            f"기대 {int(exp['전기이월부인액']):,} / 입력 {int(원(cur.get('전기이월부인액', 0))):,}")

    # 2. 이월결손금 대조
    exp_결손 = 이월결손금이월(전기결과, 전기회사)
    cur_결손 = 원(당기_회사.get("이월결손금", 0))
    add("이월결손금 이월", exp_결손 == cur_결손,
        f"기대 {int(exp_결손):,} / 입력 {int(cur_결손):,}")

    return {"ok": all(c["ok"] for c in checks), "checks": checks}
