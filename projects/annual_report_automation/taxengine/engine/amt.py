"""최저한세 — 조특법 §132.

공제·감면 후 세액이 [감면전 과세표준 × 최저한세율]에 못 미치면
그 차액만큼 공제·감면을 배제한다.

⚠️ 단순화: 이 프로젝트의 입력 모델은 손금산입·세액공제·감면·소득공제를
항목별로 구분하지 않고 `공제감면세액` 하나로 합산해 받는다. 실제 배제 순서
(시행령 §126 — 손금산입/익금불산입 → 세액공제 → 감면 → 소득공제)는 항목이
여러 개일 때만 의미가 있으므로, 항목별 이월관리가 들어오기 전까지는
합산액을 단일 배제 대상으로 취급한다.
"""

from decimal import Decimal

from taxengine.money import 절사
from taxengine.domain.rates import 최저한세율


def 계산(과세표준: Decimal, 산출세액: Decimal, 공제감면세액: Decimal, 중소기업: bool) -> dict:
    """반환: {최저한세, 배제액, 적용후공제감면세액, 적용}"""
    율 = 최저한세율(중소기업, 과세표준)
    최저한세 = 절사(과세표준 * 율)
    감면후세액 = 산출세액 - 공제감면세액

    배제액 = Decimal(0)
    if 감면후세액 < 최저한세:
        # 배제할 수 있는 건 어차피 "신청한 공제·감면세액"까지다 — 신청액이 0이면
        # 배제할 대상 자체가 없어 최저한세는 아무 영향을 주지 않는다.
        배제액 = min(공제감면세액, 최저한세 - 감면후세액)

    return {"최저한세": 최저한세, "율": 율, "배제액": 배제액,
            "적용후공제감면세액": 공제감면세액 - 배제액, "적용": 배제액 > 0}
