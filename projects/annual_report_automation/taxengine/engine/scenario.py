"""절세 시나리오 엔진 — 감가상각 방법·내용연수의 적법 조합을 열거해 세액을 비교한다.

근거: plans/PLAN-4-세무조정.md §7 (원안). 이번 범위는 원안 5개 결정 변수 중
**자산별 상각방법·내용연수 선택**만 다룬다. 나머지(배당 규모, 세액공제 당기/이월,
결산조정 계상 여부)는 이 프로젝트에 아직 그 입력·계산 경로가 없어 범위 밖 — 확장 지점으로 남긴다.

법적 제약(§7 5-2)은 새로 만들지 않는다 — engine/depreciation.py의 상각선택()이 이미
강제하는 규칙(건축물·업무용승용차는 방법 고정)을 그대로 물려받는다. 그래서 이 모듈이
만드는 선택지에는 애초에 불법 조합이 없다.

⚠️ 다년 관점 경고(§7 5-4): 감가상각 방법·내용연수를 바꾸는 건 손금 인식 **시기**를
옮기는 것뿐이다. 자산의 생애 전체 상각액 합계는 방법과 무관하게 취득가액(-잔존가치)으로
고정된다. 그래서 이 엔진이 만드는 모든 조합은 절대 절감형이 아니라 전부 **과세이연형**이다
— "올해 덜 내면 내년 이후 더 낸다." `비교()`가 돌려주는 `과세이연_경고`를 항상 같이 보여줄 것.
"""

from decimal import Decimal
from itertools import product

from taxengine.engine.depreciation import 상각선택, 시부인
from taxengine.engine.tax import 계산 as 세액계산
from taxengine.domain.rates import 기준내용연수, 상각률표

과세이연_경고 = (
    "이 비교표의 모든 조합은 감가상각 방법·내용연수 선택만 바꾼 결과다. "
    "자산 생애 전체 상각액 합계는 고정이므로 여기서 '유리'한 조합은 전부 "
    "세금을 앞당겨 내거나 뒤로 미루는 것(과세이연)일 뿐, 총 부담이 줄어드는 게 아니다."
)


def 자산별_선택지(자산: dict) -> list[dict]:
    """자산 1건이 고를 수 있는 적법한 (방법, 내용연수) 조합 전부.

    방법이 법으로 고정된 자산(건축물·업무용승용차)은 상각선택()이 강제하는 값 하나만
    돌려준다 — 불법 조합은 애초에 생성되지 않는다.
    """
    고정 = 상각선택(자산)
    if 고정["고정"]:
        return [{"방법": 고정["방법"], "내용연수": 고정["내용연수"]}]

    기준 = 기준내용연수.get(자산.get("구분"))
    if 기준 is None:
        return [{"방법": 자산.get("방법"), "내용연수": 자산.get("내용연수")}]

    최저, 최고 = 기준["범위"]
    조합 = [
        {"방법": 방법, "내용연수": 연수}
        for 방법 in ("정액", "정률")
        for 연수 in range(최저, 최고 + 1)
        if 상각률표.get(연수, {}).get(방법) is not None
    ]
    return 조합 or [{"방법": 자산.get("방법"), "내용연수": 자산.get("내용연수")}]


def 비교(자산목록: list[dict], 회사: dict, 기타조정_가산, 기타조정_차감,
       세액계산입력공통: dict, 최대조합수: int = 500) -> dict:
    """자산별 선택지를 전부 조합해 세액을 계산하고 낮은 순으로 정렬한다.

    자산목록: loader.자산행()으로 정규화된 dict 리스트 (회사계상액은 실제 그대로 고정).
    기타조정_가산/차감: 감가상각을 뺀 나머지 조정(추진비·승용차·명세서 등) — 시나리오 전체에서 불변.
    세액계산입력공통: engine.tax.계산()에 넘길 나머지 입력(당기순이익·이월결손금 등).

    반환: {조합들(차감납부세액 오름차순), 최선, 최다부담, 과세이연_경고}
    """
    선택지들 = [자산별_선택지(a) for a in 자산목록]
    총조합수 = 1
    for s in 선택지들:
        총조합수 *= len(s)
    if 총조합수 > 최대조합수:
        raise ValueError(f"조합이 {총조합수:,}개로 상한({최대조합수:,}개)을 넘습니다 — "
                          "자산 수를 줄이거나 max_combos를 올리세요")

    결과들 = []
    for 조합 in product(*선택지들):
        감가부인 = Decimal(0)
        감가추인 = Decimal(0)
        상세 = []
        for 자산, 선택 in zip(자산목록, 조합):
            s = 시부인(자산, 회사, 선택)
            감가부인 += s["부인액"]
            감가추인 += s["추인액"]
            상세.append({"자산": 자산["명"], "방법": 선택["방법"], "내용연수": 선택["내용연수"],
                        "부인액": s["부인액"], "추인액": s["추인액"]})

        r = 세액계산({
            **세액계산입력공통,
            "가산조정": 기타조정_가산 + 감가부인,
            "차감조정": 기타조정_차감 + 감가추인,
        })
        결과들.append({"선택": 상세, "감가부인": 감가부인, "감가추인": 감가추인,
                      "각사업연도소득": r["각사업연도소득"], "차감납부세액": r["차감납부세액"], "r": r})

    결과들.sort(key=lambda x: x["차감납부세액"])
    return {
        "조합들": 결과들, "최선": 결과들[0], "최다부담": 결과들[-1],
        "과세이연_경고": 과세이연_경고,
    }
