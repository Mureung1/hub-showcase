"""업무용승용차 관련비용 명세서 — 별지 제29호.

근거: 법인세법 §27의2 (research.md §3-11)

판정 순서:
  1. 업무전용자동차보험 미가입 → 관련비용 전액 손금불산입
  2. 운행기록부 작성 시: 관련비용 × 업무사용비율만 인정.
     미작성 시: 업무사용비율 = min(1, 1,500만원 ÷ 관련비용합계) — 사실상 1,500만원 한도(월할 없이)
  3. 인정된 관련비용 중 감가상각비는 별도로 800만원 한도 — 초과분은 손금불산입(유보로 이월)
  4. 부동산임대업 소규모법인은 800만→400만, 1,500만→500만으로 한도 절반

⚠️ 현재 반영 안 된 것 (실제 데이터 확보 시 확장):
  · 월할 계산 — 사업연도가 12개월이 아니거나 차량을 연중 취득/처분한 경우의 한도 비례 축소.
    research.md에 정확한 월할 공식이 없어 보류. 확인 전에는 사업연도가 12개월인 경우에만 쓸 것.
  · 전기이월 감가상각한도초과액의 당기 추인 (일반 감가상각의 전기이월부인액 추인과 같은 구조).
  · 리스·렌트 차량의 "감가상각비상당액" 환산(리스료−보험료 등, 렌트료×70%) — 취득 차량만 가정.
  · 8천만원 이상 법인차 연두색 번호판 미부착 시 전액부인(2024.1.1~) — 입력에 없음, 별도 체크 필요.

⚠️ 파이프라인 미통합: 차량별 관련비용 원시 데이터(assets.csv와 별개 스키마)가 아직 어느
CSV에도 없다. 실제 차량 데이터가 들어오면 이 모듈을 pipeline.py에 연결한다.
"""

from decimal import Decimal

from taxengine.money import 원, 절사
from taxengine.domain.rates import 업무용승용차 as 파라미터


def _한도(키: str, 소규모임대법인: bool) -> Decimal:
    한도 = 파라미터[키]
    return 절사(한도 * 파라미터["소규모임대법인_한도율"]) if 소규모임대법인 else 한도


def 판정(차량: dict, 소규모임대법인: bool = False) -> dict:
    """차량 1대의 관련비용 손금 판정.

    차량 입력 키: 감가상각비, 기타관련비용(유류비·보험료·수선비·자동차세·통행료 합계),
                전용보험가입(bool), 운행기록부작성(bool), 업무사용비율(0~100, 운행기록부 작성 시만)
    """
    감가한도 = _한도("감가상각_한도", 소규모임대법인)
    무기록한도 = _한도("운행기록부미작성_한도", 소규모임대법인)

    감가상각비 = 원(차량.get("감가상각비", 0))
    기타비용 = 원(차량.get("기타관련비용", 0))
    관련비용합계 = 감가상각비 + 기타비용

    if not 차량.get("전용보험가입"):
        return {
            "관련비용합계": 관련비용합계, "업무사용비율": Decimal(0),
            "손금인정액": Decimal(0), "감가상각한도초과": Decimal(0),
            "손금불산입액": 관련비용합계,
            "사유": "업무전용자동차보험 미가입 → 전액 손금불산입(법인세법 §27의2)",
        }

    if 차량.get("운행기록부작성"):
        업무비율 = min(Decimal(1), 원(차량.get("업무사용비율", 0)) / Decimal(100))
        사유 = f"운행기록부 작성 — 업무사용비율 {업무비율 * 100}%"
    elif 관련비용합계 > 0:
        업무비율 = min(Decimal(1), 무기록한도 / 관련비용합계)
        사유 = f"운행기록부 미작성 — 한도 {무기록한도:,}원 이내만 인정"
    else:
        업무비율 = Decimal(0)
        사유 = "운행기록부 미작성, 관련비용 없음"

    인정감가상각비_비율적용 = 절사(감가상각비 * 업무비율)
    감가상각한도초과 = max(Decimal(0), 인정감가상각비_비율적용 - 감가한도)
    인정감가상각비 = min(인정감가상각비_비율적용, 감가한도)
    인정기타비용 = 절사(기타비용 * 업무비율)

    손금인정액 = 인정감가상각비 + 인정기타비용
    업무외분 = 관련비용합계 - 인정감가상각비_비율적용 - 인정기타비용
    손금불산입액 = 업무외분 + 감가상각한도초과

    return {
        "관련비용합계": 관련비용합계, "업무사용비율": 업무비율,
        "손금인정액": 손금인정액, "감가상각한도초과": 감가상각한도초과,
        "손금불산입액": 손금불산입액, "사유": 사유,
    }


def 처분손실판정(처분손실, 소규모임대법인: bool = False) -> dict:
    """차량 처분손실도 감가상각비와 같은 한도(800만/400만)를 쓴다."""
    한도 = _한도("감가상각_한도", 소규모임대법인)
    처분손실 = 원(처분손실)
    한도초과 = max(Decimal(0), 처분손실 - 한도)
    return {"인정액": min(처분손실, 한도), "한도초과": 한도초과}
