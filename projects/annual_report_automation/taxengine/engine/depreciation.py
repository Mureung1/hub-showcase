"""감가상각 엔진 — 세법상 상각범위액 계산 + 시부인.

⚠️ 두 개념을 절대 혼동하지 않는다:
  · 상각범위액 = 세법이 허용하는 그 해의 최대 손금 (이 파일이 계산)
  · 회사계상액 = 회사가 장부에 실제로 적은 감가상각비 (입력으로 받음)
  시부인 = 둘의 비교. 초과분은 손금불산입(유보), 부족분은 전기 부인액 한도 내 추인.

근거: 법인세법 §23, 시행령 §26, 시행규칙 §15
"""

from datetime import date
from decimal import Decimal

from taxengine.money import 원, 절사
from taxengine.domain.rates import 상각률표, 기준내용연수


def 사용월수(취득일: str, 개시일: str, 종료일: str) -> int:
    """당기 사용 월수 (신규 취득 시 월할, 취득한 달을 1개월로 산입).

    근거: 법인세법 시행령 §26⑨
    """
    취득 = date.fromisoformat(취득일)
    개시 = date.fromisoformat(개시일)
    종료 = date.fromisoformat(종료일)
    if 취득 <= 개시:
        return 12
    if 취득 > 종료:
        return 0
    return (종료.year - 취득.year) * 12 + (종료.month - 취득.month) + 1


def 상각선택(자산: dict, 선택: dict | None = None) -> dict:
    """상각방법·내용연수 결정. 방법고정 자산(건축물·업무용승용차)은 선택을 무시하고 법정값 강제.

    → 절세 시나리오가 불법 조합(건물 정률 등)을 만드는 것 자체가 불가능해진다.
    """
    선택 = 선택 or {}
    # 업무용승용차: 2016.1.1 이후 취득분은 5년 정액법 강제 (법인세법 §27의2)
    if 자산.get("업무용승용차"):
        return {"방법": "정액", "내용연수": 5, "고정": True,
                "사유": "업무용승용차 5년 정액 강제(§27의2)"}
    # 건축물: 정액법만 허용 (시행령 §26)
    고정방법 = 기준내용연수.get(자산.get("구분"), {}).get("방법고정")
    if 고정방법:
        return {"방법": 고정방법,
                "내용연수": 선택.get("내용연수", 자산.get("내용연수")),
                "고정": True,
                "사유": f"{자산['구분']}은 {고정방법}법만 허용(시행령 §26)"}
    return {"방법": 선택.get("방법", 자산.get("방법")),
            "내용연수": 선택.get("내용연수", 자산.get("내용연수")),
            "고정": False}


def 상각범위액(자산: dict, 선택: dict, 회사: dict) -> dict:
    """세법상 상각범위액 (세법 공식은 잔존가치를 빼지 않는다).

    정액법: 취득가액 × 정액률
    정률법: 미상각잔액(취득가액 − 기왕 상각누계) × 정률률
    """
    월수 = 사용월수(자산["취득일"], 회사["사업연도개시일"], 회사["사업연도종료일"])
    if 월수 == 0:
        return {"금액": Decimal(0), "월수": 0, "율": Decimal(0), "기준액": Decimal(0), "산식": "당기 미사용"}

    율 = 상각률표.get(선택["내용연수"], {}).get(선택["방법"])
    if 율 is None:
        raise ValueError(
            f"상각률 없음: 내용연수 {선택['내용연수']}년 · {선택['방법']}법 "
            "(건축물 40년은 정액법만 허용)"
        )

    정률 = 선택["방법"] == "정률"
    취득가 = 원(자산["취득가"])
    기준액 = 취득가 - 원(자산.get("기초누계", 0)) if 정률 else 취득가
    연액 = 절사(기준액 * 율)
    금액 = 절사(연액 * 월수 / 12)

    기준명 = "미상각잔액" if 정률 else "취득가액"
    산식 = f"{기준명} {기준액:,} × {선택['방법']}률 {율}"
    if 월수 < 12:
        산식 += f" × {월수}/12개월"
    산식 += f" = {금액:,}"

    return {"금액": 금액, "월수": 월수, "율": 율, "기준액": 기준액, "산식": 산식}


def 시부인(자산: dict, 회사: dict, 선택지정: dict | None = None) -> dict:
    """시부인 — 회사계상액과 상각범위액을 비교해 세무조정을 산출한다. 자산별 계산(통산 금지)."""
    선택 = 상각선택(자산, 선택지정)
    범위 = 상각범위액(자산, 선택, 회사)
    계상 = 원(자산["회사계상액"]) if 자산.get("회사계상액") is not None else 범위["금액"]
    전기부인 = 원(자산.get("전기이월부인액", 0))
    차이 = 계상 - 범위["금액"]

    부인액 = Decimal(0)
    추인액 = Decimal(0)
    if 차이 > 0:
        부인액 = 차이  # 손금불산입(유보)
        판정 = "상각부인 → 손금불산입(유보)"
    elif 차이 < 0:
        추인액 = min(-차이, 전기부인)  # 시인부족액 한도 내에서 전기 부인액 추인(△유보)
        판정 = "시인부족 → 전기부인액 손금추인(△유보)" if 추인액 > 0 else "시인부족 → 소멸"
    else:
        판정 = "일치"

    return {
        "자산": 자산["명"], "방법": 선택["방법"], "내용연수": 선택["내용연수"], "방법고정": 선택["고정"],
        "회사계상액": 계상, "상각범위액": 범위["금액"], "산식": 범위["산식"],
        "부인액": 부인액, "추인액": 추인액, "판정": 판정,
    }
