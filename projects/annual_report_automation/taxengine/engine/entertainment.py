"""기업업무추진비(구 접대비) 조정명세서 — 별지 제23호(갑·을).

두 단계 검증(research.md §3-10):
  ① 적격증빙 검증(을): 건당 3만원 초과 지출 중 적격증빙 없는 분 → 한도와 무관하게 전액 손금불산입
  ② 한도 검증(갑): 한도 = 기본한도×월수/12 + 수입금액 구간별 적용률. 소규모임대법인 50% 축소

근거: 법인세법 §25

⚠️ R2 (plans/PLAN-4-세무조정.md): 적격증빙 없는 금액은 건별 증빙유형 태그가 있어야 자동 판정되는데
지금은 그 태그가 없다. 그래서 `적격증빙없는금액`은 여전히 사람이 입력한다 — 이 모듈이 대신 자동화하는
건 한도 계산(수입금액×적용률 구간 누적, 소규모임대법인 축소)이다.
"""

from decimal import Decimal

from taxengine.money import 원, 절사
from taxengine.domain.rates import 기업업무추진비 as 파라미터


def 수입금액한도(수입금액: Decimal) -> dict:
    """수입금액을 구간별 적용률로 누적 적용 (누진세액과 같은 구간 로직)."""
    이전상한 = Decimal(0)
    금액 = Decimal(0)
    내역 = []
    for 구간 in 파라미터["수입금액적용률"]:
        구간액 = max(Decimal(0), min(수입금액, 구간["상한"]) - 이전상한)
        if 구간액 > 0:
            부분 = 절사(구간액 * 구간["율"])
            금액 += 부분
            내역.append({"상한": 구간["상한"], "금액": 구간액, "율": 구간["율"], "적용액": 부분})
        이전상한 = 구간["상한"]
        if 수입금액 <= 구간["상한"]:
            break
    return {"금액": 금액, "내역": 내역}


def 한도(수입금액, 월수: int, 중소기업: bool, 소규모임대법인: bool = False) -> dict:
    """반환: {기본한도, 수입금액분, 한도, 소규모임대법인_축소적용}"""
    수입금액 = 원(수입금액)
    기본 = 파라미터["기본한도_중소"] if 중소기업 else 파라미터["기본한도_일반"]
    기본한도 = 절사(기본 * 월수 / 12)
    수입금액분 = 수입금액한도(수입금액)
    합계 = 기본한도 + 수입금액분["금액"]
    if 소규모임대법인:
        합계 = 절사(합계 * 파라미터["소규모임대법인_한도율"])
    return {"기본한도": 기본한도, "수입금액분": 수입금액분["금액"], "한도": 합계,
            "소규모임대법인_축소적용": 소규모임대법인}


def 시부인(회사계상액, 적격증빙없는금액, 한도결과: dict) -> dict:
    """적격증빙 없는 지출은 한도와 무관하게 전액 손금불산입, 나머지만 한도와 비교."""
    회사계상액 = 원(회사계상액)
    적격증빙없는금액 = 원(적격증빙없는금액)
    적격지출 = max(Decimal(0), 회사계상액 - 적격증빙없는금액)
    한도초과 = max(Decimal(0), 적격지출 - 한도결과["한도"])
    손금불산입합계 = 적격증빙없는금액 + 한도초과
    return {
        "회사계상액": 회사계상액, "적격증빙없는금액": 적격증빙없는금액,
        "적격지출": 적격지출, "한도": 한도결과["한도"], "한도초과": 한도초과,
        "손금불산입합계": 손금불산입합계,
    }
