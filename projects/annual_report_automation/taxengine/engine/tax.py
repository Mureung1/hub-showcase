"""별지 제3호 — 법인세 과세표준 및 세액조정계산서.

research.md §1 "법인세 계산 구조"를 그대로 옮긴 세액 계산의 본체.
근거: 법인세법 §13(과세표준), §55(세율), §13①(이월결손금)
"""

from decimal import Decimal

from taxengine.money import 원, 절사
from taxengine.domain.rates import 법인세율, 지방소득세율, 이월결손금공제율


def 누진세액(과세표준: Decimal, 세율표: list) -> dict:
    """누진 구간 합산. 과세표준을 구간별로 쪼개 각 세율을 적용한다."""
    이전상한 = Decimal(0)
    세액 = Decimal(0)
    내역 = []
    for 구간 in 세율표:
        구간액 = max(Decimal(0), min(과세표준, 구간["상한"]) - 이전상한)
        if 구간액 > 0:
            부분 = 절사(구간액 * 구간["율"])
            세액 += 부분
            내역.append({"구간": 구간.get("구간", ""), "금액": 구간액, "율": 구간["율"], "세액": 부분})
        이전상한 = 구간["상한"]
        if 과세표준 <= 구간["상한"]:
            break
    return {"세액": 세액, "내역": 내역}


def 계산(입력: dict) -> dict:
    """별지3 세액 계산.

    입력 키:
      당기순이익, 가산조정, 차감조정, 기부금한도초과, 이월결손금, 비과세소득, 소득공제,
      공제감면세액, 가산세, 기납부세액, 중소기업, 사업연도개시일
    """
    당기순이익 = 원(입력["당기순이익"])
    가산조정 = 원(입력.get("가산조정", 0))
    차감조정 = 원(입력.get("차감조정", 0))
    기부금한도초과 = 원(입력.get("기부금한도초과", 0))
    이월결손금 = 원(입력.get("이월결손금", 0))
    비과세소득 = 원(입력.get("비과세소득", 0))
    소득공제 = 원(입력.get("소득공제", 0))
    공제감면세액 = 원(입력.get("공제감면세액", 0))
    가산세 = 원(입력.get("가산세", 0))
    기납부세액 = 원(입력.get("기납부세액", 0))
    중소기업 = 입력.get("중소기업", False) is True
    개시일 = 입력["사업연도개시일"]

    각사업연도소득 = 당기순이익 + 가산조정 - 차감조정 + 기부금한도초과

    # 이월결손금 공제한도: 중소기업 100%, 일반 80%
    공제율 = 이월결손금공제율["중소"] if 중소기업 else 이월결손금공제율["일반"]
    이월결손금공제 = min(이월결손금, 절사(max(Decimal(0), 각사업연도소득) * 공제율))

    과세표준 = max(Decimal(0), 각사업연도소득 - 이월결손금공제 - 비과세소득 - 소득공제)

    법인 = 누진세액(과세표준, 법인세율(개시일))
    산출세액 = 법인["세액"]

    # 공제·감면은 입력으로 받음 (최저한세 로직은 후속 모듈)
    차감납부세액 = 산출세액 - 공제감면세액 + 가산세 - 기납부세액

    # 지방소득세: 같은 과세표준에 독립세율 (위택스 별도 신고)
    지방 = 누진세액(과세표준, 지방소득세율(개시일))

    단계 = [
        {"부호": "",  "라벨": "결산서상 당기순이익", "금액": 당기순이익},
        {"부호": "+", "라벨": "익금산입·손금불산입", "금액": 가산조정},
        {"부호": "−", "라벨": "손금산입·익금불산입", "금액": 차감조정},
    ]
    if 기부금한도초과:
        단계.append({"부호": "+", "라벨": "기부금 한도초과", "금액": 기부금한도초과})
    단계 += [
        {"부호": "=", "라벨": "각 사업연도 소득금액", "금액": 각사업연도소득, "강조": True},
        {"부호": "−", "라벨": f"이월결손금 공제 ({'중소 100%' if 중소기업 else '일반 80%'} 한도)", "금액": 이월결손금공제},
        {"부호": "=", "라벨": "과세표준", "금액": 과세표준, "강조": True},
        {"부호": "×", "라벨": "세율", "금액": None,
         "주석": " / ".join(f"{b['구간']} {b['율'] * 100:.0f}%" for b in 법인["내역"])},
        {"부호": "=", "라벨": "산출세액", "금액": 산출세액, "강조": True},
    ]
    if 공제감면세액:
        단계.append({"부호": "−", "라벨": "공제·감면세액", "금액": 공제감면세액})
    if 가산세:
        단계.append({"부호": "+", "라벨": "가산세", "금액": 가산세})
    단계 += [
        {"부호": "−", "라벨": "기납부세액", "금액": 기납부세액},
        {"부호": "=", "라벨": "차감 납부할 세액", "금액": 차감납부세액, "강조": True, "최종": True},
    ]

    return {
        "각사업연도소득": 각사업연도소득, "이월결손금공제": 이월결손금공제, "과세표준": 과세표준,
        "산출세액": 산출세액, "세율내역": 법인["내역"],
        "공제감면세액": 공제감면세액, "가산세": 가산세, "기납부세액": 기납부세액,
        "차감납부세액": 차감납부세액,
        "지방소득세": {"과세표준": 과세표준, "산출세액": 지방["세액"], "내역": 지방["내역"]},
        "총납부세액": 차감납부세액 + 지방["세액"],
        "단계": 단계,
    }
