"""법인세비용 수렴 루프 — 2·4단계의 순환 참조를 iteration으로 해소한다.

법인세비용을 계상해야 당기순이익이 확정되고, 당기순이익이 확정돼야 4단계 세무조정으로
세액이 나오고, 세액이 나와야 법인세비용을 계상할 수 있다 (plans/PLAN-2-결산.md §4).

법인세비용은 손금불산입(기타사외유출) 조정 항목이라 **당기순이익 감소분과 가산조정
증가분이 원 단위로 정확히 상쇄**된다 → 각사업연도소득은 법인세비용 값과 무관하게 불변이고,
그래서 실무상 2회 계산(0원 가정 1회 + 산출값 반영 확인 1회)이면 수렴한다.

⚠️ 이 함수는 "종이책을 재현"하는 pipeline.py와는 다른 경로다. 재현은 이미 확정된
당기순이익(법인세비용 기 반영)을 CSV에서 그대로 읽는다. 이 함수는 아직 법인세비용이
확정되지 않은 **새 사업연도를 처음부터 계산**할 때(예: 절세 시나리오, 내년도 추정)를 위한 것.
"""

from decimal import Decimal

from taxengine.money import 원
from taxengine.engine.tax import 계산


def 수렴계산(세전당기순이익, 가산조정_세전=0, 차감조정=0, 최대반복=10, **세액계산입력) -> dict:
    """반환: {법인세비용, 당기순이익, r(별지3 결과), 회차기록, 반복횟수, 수렴}"""
    세전당기순이익 = 원(세전당기순이익)
    가산조정_세전 = 원(가산조정_세전)
    법인세비용 = Decimal(0)
    회차기록 = []

    for 회차 in range(1, 최대반복 + 1):
        당기순이익 = 세전당기순이익 - 법인세비용
        가산조정 = 가산조정_세전 + 법인세비용
        r = 계산({
            "당기순이익": 당기순이익, "가산조정": 가산조정, "차감조정": 차감조정,
            **세액계산입력,
        })
        산출법인세비용 = r["총납부세액"]
        수렴 = abs(산출법인세비용 - 법인세비용) < 1
        회차기록.append({"회차": 회차, "투입법인세비용": 법인세비용,
                        "산출법인세비용": 산출법인세비용, "수렴": 수렴})
        if 수렴:
            return {"법인세비용": 산출법인세비용, "당기순이익": 당기순이익, "r": r,
                    "회차기록": 회차기록, "반복횟수": 회차, "수렴": True}
        법인세비용 = 산출법인세비용

    return {"법인세비용": 법인세비용, "당기순이익": 당기순이익, "r": r,
            "회차기록": 회차기록, "반복횟수": 최대반복, "수렴": False}
