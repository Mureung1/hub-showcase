"""법인 프로필에서 파생되는 판정 — 여러 조정 모듈이 공유하는 회사 단위 플래그.

지금은 기업업무추진비(§25)·업무용승용차(§27의2) 두 곳에서 똑같이 쓰는
"소규모 부동산임대법인" 판정 하나뿐이다. 한 곳에서만 계산해 두 모듈이 같은 값을 쓰게 한다.
"""

from taxengine.money import 원


def 소규모임대법인여부(회사: dict) -> bool:
    """부동산임대업 주업 + 상시근로자 5인 미만 + 지배주주 지분 50% 초과 → 한도 50% 축소.

    근거: 법인세법 §25⑤(기업업무추진비), §27의2(업무용승용차) — research.md §3-10/§3-11
    """
    return (
        회사.get("부동산임대업주업") is True
        and int(str(회사.get("상시근로자수", 999)).replace(",", "")) < 5
        and 원(회사.get("지배주주지분율", 0)) > 50
    )
