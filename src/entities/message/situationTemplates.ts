export const templateCandidatesFor = (scenarioId: ScenarioId, situationId: SituationId): Candidate[] | null => {
  const toneTexts = templates[scenarioId][situationId]
  if (!toneTexts) return null

  return ([1, 2, 3] as const).map((toneLevel) => ({
    toneLevel,
    toneLabel: toneLabels[toneLevel],
    text: toneTexts[toneLevel],
  }))
}
