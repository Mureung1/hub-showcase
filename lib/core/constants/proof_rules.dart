/// 사진 인증(3주차) 압축·크기 정책의 **단일 진실원.**
///
/// **왜 Firestore에 base64로 넣나**: Storage(Blaze 요금제)를 쓰지 않기로 했다.
/// 대신 압축한 썸네일을 base64 문자열로 만들어 `users/{uid}/proofs/{questId}`
/// 문서에 담는다(성취·퀘스트 문서가 아니라 별도 문서 — 목록 조회 때마다 이미지
/// 바이트가 딸려오면 읽기 비용이 폭증한다).
///
/// **왜 크기 상한이 필수인가**: Firestore 문서 하나는 **1 MiB 하드 리밋**이다.
/// base64 인코딩은 원본 3바이트를 4문자로 바꿔 약 **33% 부풀린다.** 압축 없이
/// 폰 원본 사진(수 MB)을 넣으면 인코딩 후 리밋을 훌쩍 넘겨 문서 쓰기가 통째로
/// 실패한다. 그래서 두 단계로 막는다:
///   ① 픽업 시 압축 — 가로 [kProofMaxWidth]px · 품질 [kProofImageQuality]
///      (보통 수십 KB로 줄어든다).
///   ② 저장 직전 방어 — base64 길이가 [kMaxProofBase64Bytes]를 넘으면 거부한다
///      (화면과 저장소 **양쪽**에서. normalizeMemo 이중 방어와 같은 취지).
library;

/// image_picker 압축 시 가로 최대 픽셀. 세로는 비율에 맞춰 함께 줄어든다.
/// 썸네일 인증이라 800px면 무엇을 했는지 알아보기에 충분하다.
const int kProofMaxWidth = 800;

/// image_picker 압축 품질(0~100). 50은 알아볼 수 있으면서 파일이 작게
/// 유지되는 절충값 — 안전(작은 파일) 우선.
const int kProofImageQuality = 50;

/// 저장을 허용하는 base64 문자열의 최대 길이(= ASCII라 바이트 수와 같다).
///
/// 1 MiB(1,048,576) 하드 리밋에서 넉넉히 물러선 700 KiB로 잡는다. proof 문서엔
/// base64 외에 questId·createdAt도 함께 들어가고, 무엇보다 리밋에 바짝 붙이면
/// 압축 편차로 어쩌다 넘치는 사진이 생긴다. 여유를 둔다.
const int kMaxProofBase64Bytes = 700 * 1024;

/// 크기 상한을 넘겼을 때 사용자에게 그대로 보여줄 문구.
///
/// 시트 스낵바(첨부 단계 거부)와 저장소 방어([AppFailure])가 **같은 문구**를 쓰도록
/// 한곳에 둔다. 두 곳에 문자열을 흩뿌리면 언젠가 갈려서 안내가 어긋난다.
const String kProofTooLargeMessage = '사진이 너무 커요. 다른 사진을 골라주세요.';
