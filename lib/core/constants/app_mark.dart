import 'growth_rules.dart';

/// 앱 마크 — 5탭(홈·퀘스트 목록·상점·보관함·MY) 화면 제목 왼쪽에 붙는 도트 알.
///
/// ⚠️ **이건 "앱 마크"이지 "내 캐릭터"가 아니다.** 사용자가 참새·매로 진화해도,
/// 용·피닉스로 환생해도 **알 그대로 고정이다.** 여기를 현재 단계
/// (`stageOf(user.level, rebirth: user.rebirth)`)로 연결하고 싶어질 수 있는데,
/// 그러면 마크가 사람마다 다른 그림이 되어 "어느 앱의 어느 화면인가"를 알리는
/// 표지 기능을 잃는다. 헤더는 **화면 정체성**이고, 캐릭터 상태는 홈 히어로와 MY가
/// 이미 각각 크게 보여 준다 — 같은 정보를 헤더에 세 번째로 두지 않는다.
///
/// **왜 앱 아이콘(`assets/icon/app_icon.png`)이 아닌가** — 사용자 결정(2026-07-29):
/// 배경이 꽉 찬 초록 사각형 일러스트라 제목 옆에 초록 타일이 붙어 보이고, 30dp
/// 근처에서 디테일이 뭉개지며, **988KB가 앱 번들에 새로 추가된다**(지금은 런처
/// 전용이라 `pubspec.yaml`의 `assets:` 밖에 있다). 알 도트아트는 이미 번들에
/// 들어 있고 배경이 투명이라 추가 용량이 0이다.
abstract final class AppMark {
  /// 마크 자산 경로. **경로 리터럴을 새로 적지 않는다.**
  ///
  /// `stageOf(1)`(새 계열 1단계 = 알)이 들고 있는 경로를 그대로 참조해서,
  /// `test/core/pixel_asset_test.dart`가 이미 존재·번들 선언을 검증하는 **같은
  /// 출처**를 쓴다. 여기에 문자열 사본을 적으면 그 사본은 아무도 검증하지 않고,
  /// `PixelArt`가 로드 실패를 폴백으로 조용히 덮어 오타가 배포까지 간다
  /// (같은 이유의 상세 설명 → `empty_art.dart` 주석).
  static String get asset => _stage.asset;

  /// 로드 실패 시 대체 표시. 이것도 같은 출처에서 가져온다.
  static String get emoji => _stage.emoji;

  /// 새 계열 1단계(알). [stageOf]의 `rebirth` 기본값이 0이라 항상 새 계열이고,
  /// 레벨 1은 구간 인덱스 0이라 항상 알이다 — 성장·환생에 흔들리지 않는다.
  static final CharacterStage _stage = stageOf(1);

  /// 마크 한 변(dp). **원본 세로 106px의 정확히 1/3**이다(원본 95×106).
  ///
  /// `PixelArt.emoji`는 정사각 박스 + `BoxFit.contain`이라 제한 축이 긴 쪽(세로
  /// 106)이고, 그리기 배율이 `size / 106`으로 정해진다. 1/3을 고른 이유 셋:
  ///
  /// - **픽셀 격자**: 정수 분할이라 최근접 보간이 소스 3px마다 규칙적으로 하나를
  ///   고른다. 배율이 어중간하면 같은 굵기의 외곽선이 자리마다 다르게 뭉개진다.
  ///   이 자산은 특히 잘 맞는다 — 외곽선 굵기를 재 보면 가로 런 165개 중 120개가
  ///   **정확히 3px**이다. 1/3에서는 그 3px가 빠짐없이 1px로 내려앉는다. 1/4로
  ///   줄이면 3px 런이 살아남을지 말지가 위치에 따라 갈려 윤곽이 점선으로 끊긴다
  ///   (라이트 배경에서는 이 검은 윤곽이 형태를 지탱하는 유일한 요소다 — 몸통
  ///   크림색 `#fbe1b0`은 흰 배경 대비 1.2:1로 거의 안 보인다).
  /// - **DPR 3에서 1:1**: 35.33dp × 3 = 106 물리 px = 원본 그대로다. 요즘 폰
  ///   대부분이 3배라 실기기에서는 리샘플링이 아예 일어나지 않는다. 그래서
  ///   `FilterQuality`도 [PixelArt] 기본값(최근접)을 그대로 쓴다 — 큰 축소용
  ///   예외(0.2배 이하)에 해당하지 않는다.
  /// - **제목과의 균형**: 자산은 사방 8px가 투명 여백이라 실제로 보이는 알은
  ///   세로 90/3 = 30dp다. 제목이 32/40(`headlineLarge`)이므로 글자 높이와 거의
  ///   같게 읽힌다.
  ///
  /// **다크에서도 읽힌다.** 도트 팔레트는 테마를 따라가지 않지만, 라이트에서는
  /// 검은 윤곽(대비 20:1)이, 다크(`#0B1C30`)에서는 크림색 몸통(대비 10~16:1)이
  /// 각각 형태를 지탱한다 — 두 배경 모두에서 불투명 픽셀의 상당 비율이 3:1을
  /// 넘는다(라이트 15%, 다크 87%). 색을 보정할 이유가 없다.
  static const double size = 106 / 3;
}
