/// #4 최초 분해는 **최대 5개**까지만. 너무 많으면 "작게 시작"이라는 취지가 흐려지고
/// 오늘 안에 끝낼 수 있다는 심리적 부담 완화 효과가 떨어진다. 실제 LLM이 이보다
/// 많이 뱉어도 [DecomposeNotifier]가 앞에서 잘라 방어한다.
const int kMaxDecomposeDrafts = 5;

/// #3 개별 쪼개기(🔄)는 한 항목을 **최대 3개**의 하위 스텝으로 나눈다. 하나를
/// 3개보다 잘게 쪼개면 목록이 순식간에 불어나 오히려 시작이 막막해진다.
const int kMaxRedecomposeDrafts = 3;

/// #3 한 항목 계보에서 **재쪼개기는 최대 2번**까지만.
