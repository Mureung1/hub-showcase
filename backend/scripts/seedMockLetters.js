// Gemini 무료 티어 분당 요청 한도(15회/분)를 처음부터 안 넘기도록 배치 사이에 텀을 둔다.
// (aiClient.js에 429 자동 재시도도 추가해뒀지만, 애초에 덜 부딪히는 게 낫다.)
async function processInBatches(items, concurrency, delayMs, worker) {
  for (let i = 0; i < items.length; i += concurrency) {
    const batch = items.slice(i, i + concurrency)
    await Promise.all(batch.map(worker))
    if (i + concurrency < items.length) {
      await new Promise((resolve) => setTimeout(resolve, delayMs))
    }
  }
}

async function main() {
  console.log(`시드 대상: ${LETTERS.length}건 (기존 seed- 데이터는 먼저 삭제)`)

  await prisma.match.deleteMany({ where: { sourceLetter: { authorId: { startsWith: SEED_PREFIX } } } })
  await prisma.letter.deleteMany({ where: { authorId: { startsWith: SEED_PREFIX } } })

  const created = []
  for (const { tag, content } of LETTERS) {
    const letter = await prisma.letter.create({
      data: { authorId: `${SEED_PREFIX}${tag}`, content, envelope: 'basic' },
    })
    created.push(letter)
  }
  console.log(`편지 ${created.length}건 저장 완료. 실제 Gemini로 태깅을 시작합니다...`)

  let done = 0
  await processInBatches(created, 2, 10_000, async (letter) => {
    await tagLetter(letter.id)
    done += 1
    if (done % 10 === 0) console.log(`  ${done}/${created.length} 태깅 완료`)
  })

  const failed = await prisma.letter.count({
    where: { authorId: { startsWith: SEED_PREFIX }, taggingStatus: 'failed' },
  })
  const riskCount = await prisma.letter.count({
    where: { authorId: { startsWith: SEED_PREFIX }, riskFlag: true },
  })
  console.log(`시드 완료: ${created.length}건 중 태깅 실패 ${failed}건, Gemini가 위기신호로 판단한 편지 ${riskCount}건`)
}

main()
