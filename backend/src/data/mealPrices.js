// 전부 하드코딩하는 대신 흔한 접미사/키워드로 카테고리를 추정해 flat 3000원보다 현실적인 값을 준다.
const CATEGORY_FALLBACKS = [
  { pattern: /고기|살$|갈비|안심|등심|사태|양지|차돌|고기$/, price: 8000 },  // 육류
  { pattern: /새우|오징어|조개|생선|굴|홍합|낙지|문어|게|전복|명태|동태|갈치|삼치|꽁치|장어|멸치|액젓|젓갈|어묵/, price: 5500 }, // 수산물
  { pattern: /버섯/, price: 2500 },  // 버섯류
  { pattern: /치즈|크림|우유|버터|요거트/, price: 3500 }, // 유제품
  { pattern: /기름|오일/, price: 4500 }, // 유지류
  { pattern: /가루|분$/, price: 2200 }, // 가루류
  { pattern: /즙$|주스/, price: 2500 }, // 즙/주스
  { pattern: /장$|소스|시럽|청$|양념/, price: 3000 }, // 장/소스/양념류
];
const DEFAULT_FALLBACK_PRICE = 2200; // 나머지(대부분 채소·기타 소량 재료) 평균 근사치

// 정규화된 재료 키(id 또는 한글명)로 예상 가격을 찾는다. 표에 없으면 카테고리 키워드로 추정하고,
// 그것도 안 맞으면 기본값을 쓴다 — 예전엔 전부 `?? 3000` 한 값으로 떨어져 소량 양념이든
// 고기든 구분 없이 같은 가격이 매겨졌다.
export function resolvePrice(key) {
  if (key in mealPriceTable) return mealPriceTable[key];
  const hit = CATEGORY_FALLBACKS.find(({ pattern }) => pattern.test(key));
  return hit ? hit.price : DEFAULT_FALLBACK_PRICE;
}

