// ============================================================================
// utils/formatDistance.js — 거리(미터)를 읽기 좋은 문자열로 바꾸는 순수 함수
// ----------------------------------------------------------------------------
// [순수 함수] 같은 입력이면 항상 같은 출력이고 바깥 상태를 건드리지 않는 함수.
//   화면(React)과 무관해서 어디서든 재사용 가능하고 단위테스트도 쉽다 → 표시 로직을 UI에서 분리.
// ============================================================================

/**
 * 미터 단위 거리를 사람이 읽기 쉬운 문자열로 변환한다.
 * 1000m 미만 → "320m", 1000m 이상 → "1.2km"(소수점 첫째 자리, .0 제거).
 *
 * @param {number} meters 거리(미터)
 * @returns {string}
 */
export function formatDistance(meters) {
  // 방어 코드: 값이 없거나(NaN 포함) 숫자가 아니면 빈 문자열 반환.
  if (meters == null || Number.isNaN(meters)) return '';
  if (meters < 1000) return `${Math.round(meters)}m`; // 1km 미만 → 반올림해 "320m"
  const km = meters / 1000;
  // toFixed(1) → "1.2"(문자열). replace(/\.0$/, '')로 "2.0km"→"2km"처럼 끝의 .0 제거.
  return `${km.toFixed(1).replace(/\.0$/, '')}km`;
}
