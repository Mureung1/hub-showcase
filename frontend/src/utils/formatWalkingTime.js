// ============================================================================
// utils/formatWalkingTime.js — 도보 시간(초)을 읽기 좋은 문자열로 바꾸는 순수 함수
// ----------------------------------------------------------------------------
// [왜 프론트에서 변환하나] 백엔드는 "281초"라는 사실만 내려주고, 그걸 어떻게 보여줄지는
//   화면이 정한다(운영시간 "0900" → "09:00", 요금 0 → "전화 문의" 와 같은 원칙).
//   덕분에 나중에 표기를 바꾸고 싶어도 서버 배포 없이 이 파일만 고치면 된다.
//
// [순수 함수] 같은 입력이면 항상 같은 출력. 화면과 무관해서 재사용·테스트가 쉽다.
// ============================================================================

const SECONDS_PER_MINUTE = 60;

/**
 * 도보 소요 시간(초)을 "도보 5분" 형태로 변환한다.
 *
 * [왜 분 단위인가] 걷는 속도는 사람마다 달라서 "4분 41초"처럼 초까지 보여주면
 *   실제보다 정확해 보이는 착시(거짓 정밀도)를 준다. 지도 앱들이 분 단위로 안내하는 이유다.
 *
 * [왜 올림인가] 반올림하면 281초(4분 41초)가 "5분"이 되는 건 같지만,
 *   150초(2분 30초)는 "2분"이 되어 실제보다 짧게 안내된다.
 *   올림하면 항상 "안내한 시간 안에는 도착"이라 사용자가 손해 보지 않는다.
 *
 * @param {number|null|undefined} seconds 도보 소요 시간(초). 백엔드가 못 구하면 null.
 * @returns {string} 예: "도보 5분". 값이 없으면 빈 문자열.
 */
export function formatWalkingTime(seconds) {
  // 방어 코드: 값이 없거나 숫자가 아니면 빈 문자열(호출부가 조건부 렌더로 처리).
  if (seconds == null || Number.isNaN(seconds)) return '';

  // Math.ceil = 올림. 60초 미만이어도 최소 "1분"으로 보여준다("0분"은 어색하므로).
  const minutes = Math.max(1, Math.ceil(seconds / SECONDS_PER_MINUTE));

  return `도보 ${minutes}분`;
}
