def build() -> dict[str, list[dict[str, Any]]]:
    """테이블명 → 행 목록. 데이터베이스에 접속하지 않는다."""
    postings: list[dict[str, Any]] = []
    analyses: list[dict[str, Any]] = []

    for job in JOBS:
        spec = SPEC[job]
        normalized = normalize_posting_text(build_raw_text(spec))
        content_hash = sha256_hex(normalized)
        up_id = f"up_{content_hash[:16]}"

        postings.append({
            "user_posting_id": up_id,
            "content_hash": content_hash,
            "normalized_text": normalized,
            "char_length": len(normalized),
            "job_role_id": job,
            "detected_by": DETECTED_BY,
            "first_seen_at": FIRST_SEEN_AT,
        })

        payloads = {
            "interpretation": build_interpretation_payload(job, spec, up_id),
            "strategy": build_strategy_payload(job, spec, up_id),
            "roadmap": build_roadmap_payload(job, spec, up_id),
        }
        for output_type, payload in payloads.items():
            analyses.append({
                "user_analysis_id": f"ua_{content_hash[:16]}_{output_type}",
                "user_posting_id": up_id,
                "analysis_version": f"an_demo_{job}",
                "taxonomy_version_id": f"tx_demo_{job}",
                "output_type": output_type,
                "payload": payload,
                "produced_by": PRODUCED_BY,
                "generated_at": GENERATED_AT,
            })

    return {"user_postings": postings, "user_posting_analyses": analyses}


def write_samples(root: Path) -> list[Path]:
    """시연에서 복사해 붙여넣을 원문 세 건."""
    written: list[Path] = []
    directory = root / "sample_postings"
    directory.mkdir(parents=True, exist_ok=True)
    for job in JOBS:
        path = directory / f"{job}.txt"
        path.write_text(build_raw_text(SPEC[job]), encoding="utf-8")
        written.append(path)
    return written


