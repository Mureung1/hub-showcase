def build_raw_text(spec: dict[str, Any]) -> str:
    """붙여넣기용 공고 원문. raw_sections 의 문장을 그대로 담는다."""
    lines: list[str] = [f"{spec['company']} {spec['title']} 채용", ""]
    lines.append("[회사 소개]")
    lines.extend(spec["intro"])
    for section, entries in spec["sections"]:
        lines.append("")
        lines.append(f"[{section}]")
        lines.extend(f"- {entry[1]}" for entry in entries)
    lines.append("")
    lines.append("[전형절차]")
    lines.extend(f"- {step}" for step in spec["process"])
    lines.append("")
    lines.append("[복리후생]")
    lines.extend(f"- {item}" for item in spec["benefits"])
    lines.append("")
    return "\n".join(lines)


def build_marks(spec: dict[str, Any]) -> dict[str, Any]:
    """섹션 사양에서 raw_sections 와 세 종류의 해석 카드를 함께 만든다.

    번호는 종류별 등장 순서대로 부여하므로 표시와 카드가 어긋날 수 없다.
    """
    raw_sections: list[dict[str, Any]] = []
    interpretations: list[dict[str, Any]] = []
    baseline_notes: list[dict[str, Any]] = []
    signal_notes: list[dict[str, Any]] = []
    mark_n = base_n = note_n = 0

    for section, entries in spec["sections"]:
        rendered: list[dict[str, Any]] = []
        for entry in entries:
            kind, text = entry[0], entry[1]
            line: dict[str, Any] = {
                "text": text, "mark_n": None, "note_n": None, "base_n": None, "base_ref": None,
            }
            if kind == "mark":
                mark_n += 1
                line["mark_n"] = mark_n
                interpretations.append({
                    "n": mark_n, "title": entry[2], "body": entry[3],
                    "confidence": entry[4], "ratio": entry[5],
                    "sources": [{"type": "posting", "url": None}],
                })
            elif kind == "base":
                base_n += 1
                line["base_n"] = base_n
                line["base_ref"] = entry[2]
                baseline_notes.append({"n": base_n, "base_ref": entry[2], "body": entry[3]})
            elif kind == "note":
                note_n += 1
                line["note_n"] = note_n
                signal_notes.append({"n": note_n, "title": entry[2], "body": entry[3]})
            else:  # pragma: no cover - 사양 오타 방어
                raise ValueError(f"알 수 없는 줄 종류: {kind}")
            rendered.append(line)
        raw_sections.append({"section": section, "lines": rendered})

    return {
        "raw_sections": raw_sections,
        "interpretations": interpretations,
        "baseline_notes": baseline_notes,
        "signal_notes": signal_notes,
    }


