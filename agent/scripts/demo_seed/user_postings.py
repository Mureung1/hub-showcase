def build_interpretation_payload(job: str, spec: dict[str, Any], up_id: str) -> dict[str, Any]:
    """CONTRACT 5장 B."""
    marks = build_marks(spec)
    summary = spec["summary"]
    posting = {
        "posting_id": up_id,
        "company": spec["company"],
        "title": spec["title"],
        "summary": {
            "n": None, "title": summary["title"], "body": summary["body"],
            "confidence": summary["confidence"], "ratio": summary["ratio"],
            "sources": [{"type": "posting", "url": None}],
        },
        "raw_sections": marks["raw_sections"],
        "interpretations": marks["interpretations"],
        "baseline_notes": marks["baseline_notes"],
        "signal_notes": marks["signal_notes"],
        "unchanged_note": spec["unchanged_note"],
    }
    return {
        "job": job,
        "scope": {"level": "posting", "cluster_tag": None, "posting_id": up_id},
        "baseline": [
            {"item_id": cc(job, slug), "title": title, "desc": desc,
             "freq_pct": freq, "required_ratio": ratio}
            for slug, title, desc, freq, ratio in spec["baseline"]
        ],
        "deviations": [
            {"item_id": cc(job, slug), "topic": topic, "baseline": base, "deviation": dev,
             "evidence": evidence, "explanation": explanation, "confidence": confidence,
             "ratio": ratio, "related_stat": related}
            for slug, topic, base, dev, evidence, explanation, confidence, ratio, related
            in spec["deviations"]
        ],
        "unchanged": [
            {"item_id": cc(job, slug), "title": title, "note": note}
            for slug, title, note in spec["unchanged"]
        ],
        "posting": posting,
        "agent_version": AGENT_VERSION,
        "source": SOURCE,
    }


def build_strategy_payload(job: str, spec: dict[str, Any], up_id: str) -> dict[str, Any]:
    """CONTRACT 5장 C."""
    checklist = [
        {
            "item_id": cc(job, slug), "title": title, "subtitle": subtitle, "reason": reason,
            "evidence_needed": evidence, "channels": list(channels), "kind": kind,
            "is_deviation": dev_n is not None, "dev_n": dev_n, "required": required,
            "have": False,
        }
        for slug, title, subtitle, reason, evidence, channels, kind, dev_n, required
        in spec["checklist"]
    ]
    portfolio = {
        "highlights": [
            {"title": title, "body": body, "tips": list(tips),
             "linked_item_ids": [cc(job, s) for s in linked]}
            for title, body, tips, linked in spec["highlights"]
        ],
        "intro_orders": [{"cluster": spec["cluster"], "steps": list(spec["intro_steps"])}],
    }
    essay = [
        {
            "kind": kind, "title": title, "body": body,
            "narrative": (
                None if narrative is None
                else {"problem": narrative[0], "solve": narrative[1], "growth": narrative[2]}
            ),
            "sample_sentence": sample, "tips": list(tips),
            "linked_item_ids": [cc(job, s) for s in linked],
        }
        for kind, title, body, narrative, sample, tips, linked in spec["essay"]
    ]
    interview = [
        {"kicker": kicker, "question": question, "followups": list(followups), "point": point,
         "linked_item_ids": [cc(job, s) for s in linked]}
        for kicker, question, followups, point, linked in spec["interview"]
    ]
    return {
        "job": job,
        "scope": {"level": "posting", "cluster_tag": None, "posting_id": up_id},
        "checklist": checklist,
        "portfolio": portfolio,
        "essay": essay,
        "interview": interview,
        "agent_version": AGENT_VERSION,
        "source": SOURCE,
    }


def build_roadmap_payload(job: str, spec: dict[str, Any], up_id: str) -> dict[str, Any]:
    """CONTRACT 5장 D."""
    meta = {
        slug: {"title": title, "kind": kind, "dev_n": dev_n, "required": required}
        for slug, title, _subtitle, _reason, _evidence, _channels, kind, dev_n, required
        in spec["checklist"]
    }

    def fills(items: Any) -> list[dict[str, str]]:
        return [{"item_id": cc(job, slug), "label": label, "kind": kind}
                for slug, label, kind in items]

    project_steps = [
        {
            "n": n, "phase": phase, "weeks": weeks, "priority": priority, "title": title,
            "body": body, "deliverable": deliverable, "fills": fills(fill_items),
            "reason_title": reason_title, "reason": reason, "tags": list(tags),
        }
        for n, phase, weeks, priority, title, body, deliverable, fill_items, reason_title, reason, tags
        in spec["project_steps"]
    ]
    study_tracks = [
        {
            "phase": phase, "priority": priority, "title": title, "depth": depth,
            "reason_title": reason_title, "reason": reason, "fills": fills(fill_items),
        }
        for phase, priority, title, depth, reason_title, reason, fill_items
        in spec["study_tracks"]
    ]
    check_rows = [
        {
            "item_id": cc(job, slug), "title": meta[slug]["title"], "kind": meta[slug]["kind"],
            "is_deviation": meta[slug]["dev_n"] is not None, "dev_n": meta[slug]["dev_n"],
            "required": meta[slug]["required"], "source_step": source_step,
        }
        for slug, source_step in spec["check_rows"]
    ]
    return {
        "job": job,
        "scope": {"level": "posting", "cluster_tag": None, "posting_id": up_id},
        "project_steps": project_steps,
        "study_tracks": study_tracks,
        "check_rows": check_rows,
        "agent_version": AGENT_VERSION,
        "source": SOURCE,
    }


