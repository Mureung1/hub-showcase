// 친목·소모임·스터디·동아리 모집 노이즈 판별. 이력에 별 도움 안 되는 캐주얼 모임 공고를 걸러낸다.
// 링커리어 동아리(activityTypeID 2) 등에서 '친목/스포츠' 카테고리 태그가 안 붙은 채 새는 것들을 제목·본문으로 잡는다.
// 원칙: 제외는 되돌리기 어려우니 확실한 것만 노이즈로 본다. 애매하면 통과(제외될 바엔 뜨는 게 낫다).

// 예외 키워드: 제목·본문에 있으면 노이즈 신호가 있어도 안 지운다.
// - 공모전·서포터즈·대외활동: 우리 수집 대상
// - 지원사업·보조금·활동 지원 등: '동아리/소모임을 지원(펀딩)하는 지자체 사업'은 캐주얼 모임이 아니라 legit.
//   (예: "서울 동아리ON 대학생 동아리 지원", "청년 소모임 지원사업")
const KEEP = /공모전|서포터즈|대외활동|지원사업|보조금|활동\s*지원|동아리\s*지원|소모임\s*지원/;

// 확실한 노이즈 신호.
const NOISE = [
  /소모임/,                              // 거의 항상 캐주얼 모임
  /친목/,                                // 친목 동아리·모임
  /원데이/,                              // 원데이 클래스 = 취미 유료/체험 클래스, 이력용 대외활동 아님
  /스터디\s*원?\s*모집/,                 // 스터디(원) 모집
  /동아리[\s\S]{0,12}(부원|회원|신입|신규|모집)/,  // 동아리 + 모집 신호
  /(부원|회원|신입|신규|모집)[\s\S]{0,12}동아리/,  // 순서 반대
];

// 제목(+본문) 한 덩어리를 받아 노이즈면 true. 호출부는 `${title} ${text}`를 넘긴다.
export function isClubNoise(text) {
  const t = text || "";
  if (KEEP.test(t)) return false; // 예외 먼저: 대상 키워드 있으면 무조건 통과
  return NOISE.some((re) => re.test(t));
}

// 선정결과·합격자 발표 = 지원하는 자리가 아니라 이미 끝난 결과 공지라 노이즈.
const RESULT = /선정\s*결과|결과\s*발표|합격자\s*발표|최종\s*선정자|당선작?\s*발표|선정자\s*발표/;
export function isResultAnnouncement(text) {
  return RESULT.test(text || "");
}

// 채용·계약직 등 취업 공고는 이 서비스(대외활동·공모전·장학) 범위 밖이라 노이즈.
// 단 인턴십(대외활동성일 수 있음)·공모전·서포터즈·대외활동·장학이 있으면 안 지운다(오제외 방지).
const JOB = /채용|계약직|기간제|정규직|아르바이트|알바/;
// 인턴십·서포터즈는 대외활동성, 해커톤·경진대회·대회·공모는 그 자체가 기회라 '채용' 단어가 있어도 안 지운다.
// (예: "OpenAI 채용 해커톤"은 해커톤이지 채용 공고가 아님)
const JOB_KEEP = /인턴|공모전|서포터즈|대외활동|장학|해커톤|경진대회|대회|공모/;
export function isJobPosting(text) {
  const t = text || "";
  if (JOB_KEEP.test(t)) return false;
  return JOB.test(t);
}
